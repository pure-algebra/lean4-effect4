let t10 () =
  let field k = function J.Object f -> List.assoc_opt k f | _ -> None in
  let parse s = match Kit.Json.parse s with Ok j -> j | Error e -> failwith e in
  let call m = Option.map parse (Kit_serve.mcp_line (Kit.Json.render m)) in
  let rpc ?id meth params =
    J.Object ([ ("jsonrpc", J.String "2.0"); ("method", J.String meth); ("params", J.Object params) ]
              @ match id with Some i -> [ ("id", J.Int i) ] | None -> []) in
  let result r = Option.bind r (field "result") in
  check "T10 initialize names the server"
    (Option.bind (result (call (rpc ~id:1 "initialize" []))) (field "serverInfo")
     |> Option.map (fun j -> field "name" j = Some (J.String "effect4-kit")) = Some true);
  check "T10 a notification has no reply" (call (rpc "notifications/initialized" []) = None);
  (match Option.bind (result (call (rpc ~id:2 "tools/list" []))) (field "tools") with
   | Some (J.Array ts) ->
     check "T10 six tools"
       (List.filter_map (field "name") ts
        = List.map (fun n -> J.String n) [ "check"; "run"; "probe"; "frames"; "explore"; "outside" ])
   | _ -> check "T10 tools/list" false);
  let tape = J.Array (List.map Kit.Json.exit_json (units 4)) in
  let args = [ ("name", J.String "run");
               ("arguments", J.Object [ ("program", Kit.Json.program_json doubling);
                                        ("rows", Kit.Json.rows_json [ echo ]); ("tape", tape) ]) ] in
  let text r = match Option.bind (result r) (field "content") with
    | Some (J.Array [ c ]) -> (match field "text" c with Some (J.String t) -> Some (parse t) | _ -> None)
    | _ -> None in
  (match text (call (rpc ~id:3 "tools/call" args)) with
   | Some answer ->
     check "T10 run finishes" (field "status" answer = Some (J.String "finished"));
     check "T10 the machine agrees" (field "machine" answer = Some (J.String "agrees"))
   | None -> check "T10 tools/call answers" false);
  check "T10 an unknown method is an error"
    (Option.bind (call (rpc ~id:4 "nope" [])) (field "error") <> None);
  let bad = [ ("name", J.String "check"); ("arguments", J.Object [ ("program", J.Int 3) ]) ] in
  check "T10 an unreadable program is the tool's error"
    (Option.bind (result (call (rpc ~id:5 "tools/call" bad))) (field "isError") = Some (J.Bool true));
  let fork = Eff_withFiber (ActionTerm_fork (Eff_succeed (A.nat 7), { start_immediately = false; daemon = false; mask_mode = MaskMode_inherit })) in
  let line = Kit.Json.render (J.Object [ ("op", J.String "run"); ("program", Kit.Json.program_json fork) ]) in
  check "T10 a forked program runs on the machine"
    (field "via" (parse (Kit_serve.serve_line line)) = Some (J.String "machine"))

let t11 () =
  let add = A.row "Todos.add" ~request:Ty_string ~answer:(Ty_list Ty_string) ~error:Ty_string () in
  let app = Kit.app ~rows:[ add ] () in
  let p = match A.build ~app A.(let* todos = perform "Todos.add" (str "milk") in
                                 if_ (length todos < nat 2) ~then_:(succeed (length todos)) ~else_:(fail (str "full"))) with
    | Ok e -> e | Error _ -> assert false in
  let replies = Kit.replies app 0 in
  check "T11 every drawn reply fits its row" (List.for_all (fun ex -> Kit.reply_fault app 0 ex = None) replies);
  let paths = Kit.explore app ~budget:8 ~width:64 p in
  let exits = List.filter_map (fun (path : Kit.path) -> match path.stop with Kit.Stop_finished ex -> Some ex | _ -> None) paths in
  check "T11 a path for each branch and each failure"
    (List.length paths = List.length replies
     && List.mem (Kit.succeed (Val_nat 0)) exits && List.mem (Kit.succeed (Val_nat 1)) exits
     && List.mem (Kit.fail (Val_str "full")) exits);
  check "T11 each path's tape replays it on the machine"
    (List.for_all (fun path -> Kit_machine.agree_path path (Kit_machine.run app Kit.Host.tape (Kit.tape_of path) p)) paths)

let t12 () =
  let contains s sub =
    let n = String.length sub in
    let rec go i = i + n <= String.length s && (String.sub s i n = sub || go (i + 1)) in
    go 0 in
  let count s sub =
    let n = String.length sub in
    let rec go i acc = if i + n > String.length s then acc else go (i + 1) (if String.sub s i n = sub then acc + 1 else acc) in
    go 0 0 in
  let frames = Kit.frames app ~limit:6 Kit.Host.tape (units 4) doubling in
  let settled = Kit.settle app Kit.Host.tape (units 4) doubling in
  let page = Kit_view.page (Kit_view.data ~title:"doubling" ~app ~frames ~settled ~paths:[]) in
  check "T12 the page is one file with its data"
    (contains page "<!doctype html>" && contains page "const DATA = " && count page "<script>" = 1);
  let sneaky = build A.(succeed (str "</script><b>")) in
  let frames' = Kit.frames app ~limit:1 Kit.Host.silent () sneaky in
  let settled' = Kit.settle app Kit.Host.silent () sneaky in
  let page' = Kit_view.page (Kit_view.data ~title:"x" ~app ~frames:frames' ~settled:settled' ~paths:[]) in
  check "T12 a value cannot end the script" (count page' "</script>" = 1);
  let page'' = Kit_view.page (Kit_view.data ~title:"forever" ~app ~frames:(Kit.frames app ~limit:3 Kit.Host.silent () forever)
                                ~settled:(Kit.settle ~limit:3 app Kit.Host.silent () forever) ~paths:[]) in
  check "T12 an unsettled verdict is a finite probe" (contains page'' "a finite probe, not a divergence")

