(* test_kit.ml -- the native kit's lane.

   What it is: the kit's behaviours, checked on the examples the Rocq development checks
   (docs/research/2026-10-16-itrees/rocq/BudgetCheck.v) and on Lean's fixture verdicts.txt beside
   this file (GENERATED by write.lean, `make gen-fixtures`): the 408 programs of the printed
   corpus's sources, each with its canonical bytes, Lean's verdict and Lean's JSON print.
   Depends on: Effect4_kit (Kit, Kit_json, Kit_author, Kit_gen), Eff_types, Eff_wire.

   Properties:
   T1  The call tree's runs: the doubling loop under a tape of four replies settles at budget 5,
       finished with 16 after four calls; under three it waits on row 0 with 8; a loop that is
       always true and calls nothing is unsettled at every limit tried; a definition that calls
       itself at once is unsettled too; each frame extends the one before; `settle` finds the
       least budget a linear scan finds, on loops of 0 to 40 rounds.       tested
   T2  The JSON text parser reads RFC 8259 JSON with integer numbers and refuses the rest with an
       offset.                                                              tested
   T3  JSON: a program, a row table and a tape print and read back to themselves. On the
       fixture, Lean's JSON print reads to the program its bytes decode to, and the kit prints
       Lean's JSON, up to the order of an object's keys (Lean's printer sorts them).  tested
   T4  The authoring builders: the doubling loop built by name is the raw one; an unbound row or
       definition is refused by name; the built doubling types at Effect<number, never>.  tested
   T5  The lowered checker is Lean's: on every fixture program it types where Lean types, with
       Lean's answer and error spellings, and refuses where Lean refuses, with Lean's reason and
       address.                                                             tested
   T6  Red control: a program with a wrong request type is refused by the checker, and the same
       program with the right one types, so T4 and T5 compare verdicts that differ.  tested
   T7  Reply admission: under a guarded tape, a reply that is no member of its row's answer type
       is not applied, so the run waits at that call, and `wait_reason` names the reply and the
       fault; a failure inside the row's error column is applied; with every reply fitting, the
       guarded run is the unguarded one.                                    tested
   T8  The two runners agree (Kit_machine M3): on the examples under their tapes, and on every
       fixture program in the tree's fragment, typed or not, generators among them, the tree's
       settled run and the machine's run finish or wait alike, with the same host calls.  tested
   T9  Admission: a host row registered `deferred` is refused at admission, at its index, though
       the program types; the same row registered `external` is admitted.  tested
   T10 The protocols (Kit_serve S3, S4): over MCP, `initialize` names the server, `tools/list`
       lists the five tools, `tools/call` of `run` answers the tree's run with the machine's
       agreement, a notification has no reply, an unknown method is a JSON-RPC error and an
       unreadable program is the tool's error; over JSON lines, a forked program runs on the
       machine.                                                             tested
   T11 Exploration: the replies drawn from a row's types are members of its columns; a program that
       branches on a list's length has a path for each branch and for each failure of its error
       column; each path's tape replays the path on the machine.            tested
   T12 The view (Kit_view V1, V3): the page is one HTML file holding its data; a value whose text
       holds "</script>" does not end the script element; an unsettled run's verdict says it is a
       finite probe.                                                         tested *)

open Eff_types
open Effect4_kit
module A = Kit_author
module J = Eff_json_text

let failures = ref 0
let checks = ref 0

let check name ok =
  incr checks;
  if not ok then begin
    incr failures;
    Printf.printf "FAIL %s\n%!" name
  end

let unit_ok : Kit.exit = Kit.succeed Val_unit
let units n = List.init n (fun _ -> unit_ok)
let echo = A.row "echo" ~request:Ty_nat ~answer:Ty_unit ()
let app = Kit.app ~rows:[ echo ] ()

(* the doubling loop of Examples.v, by name *)
let doubling_src =
  A.loop ~init:(A.nat 1) ~test:(fun c -> A.(c < nat 16)) ~step:(fun c _ -> A.(c * nat 2))
    ~result:(fun c -> c) (fun c -> A.perform "echo" c)

let build p = match A.build ~app p with Ok e -> e | Error r -> failwith (A.refusal_text r)
let doubling = build doubling_src

let forever =
  build (A.loop ~init:(A.nat 0) ~test:(fun _ -> A.bool true) ~step:(fun c _ -> c)
           ~result:(fun _ -> A.unit) (fun _ -> A.succeed A.unit))

let self_call =
  build A.(program [ def "f" ~request:Ty_nat ~answer:Ty_nat (fun r -> call "f" r) ] (call "f" (nat 0)))

let stop_text : Kit.stop -> string = function
  | Kit.Stop_finished (Exit_success (Val_nat n)) -> Printf.sprintf "finished %d" n
  | Kit.Stop_finished _ -> "finished other"
  | Kit.Stop_cut -> "cut"
  | Kit.Stop_waiting (i, Val_nat n) -> Printf.sprintf "waiting %d %d" i n
  | Kit.Stop_waiting (i, _) -> Printf.sprintf "waiting %d" i

let settled_text = function
  | Kit.Settled { budget; run } ->
    Printf.sprintf "%d %s %d" budget (stop_text run.stop) (List.length (Kit.calls run))
  | Kit.Unsettled { limit; _ } -> Printf.sprintf "unsettled %d" limit

let t1 () =
  check "T1 doubling settles at 5 with 16, four calls"
    (settled_text (Kit.settle app Kit.Host.tape (units 4) doubling) = "5 finished 16 4");
  check "T1 three replies: waiting on row 0 with 8"
    (settled_text (Kit.settle app Kit.Host.tape (units 3) doubling) = "4 waiting 0 8 3");
  check "T1 the silent loop is unsettled"
    (settled_text (Kit.settle ~limit:200 app Kit.Host.silent () forever) = "unsettled 200");
  check "T1 the self call is unsettled"
    (settled_text (Kit.settle ~limit:64 app Kit.Host.silent () self_call) = "unsettled 64");
  let frames = Kit.frames app ~limit:8 Kit.Host.tape (units 4) doubling in
  let rec prefix a b = match a, b with [], _ -> true | x :: a, y :: b -> x = y && prefix a b | _ -> false in
  let rec grows = function
    | f :: (g :: _ as rest) -> prefix (Kit.calls f) (Kit.calls g) && grows rest
    | _ -> true
  in
  check "T1 frames grow" (grows frames && List.length frames = 9);
  let counter m =
    build (A.loop ~init:(A.nat 0) ~test:(fun c -> A.(c < nat m)) ~step:(fun c _ -> A.atom "succ" [ c ])
             ~result:(fun c -> c) (fun c -> A.perform "echo" c))
  in
  let linear p n =
    let rec go k =
      if k > 200 then None
      else if (Kit.probe app ~budget:k Kit.Host.tape (units n) p).stop <> Kit.Stop_cut then Some k
      else go (k + 1)
    in
    go 0
  in
  let all_least =
    List.for_all
      (fun m ->
        let p = counter m in
        let fast = match Kit.settle ~limit:200 app Kit.Host.tape (units m) p with
          | Kit.Settled { budget; _ } -> Some budget | Kit.Unsettled _ -> None in
        fast = linear p m)
      (List.init 41 Fun.id)
  in
  check "T1 settle is the least budget, loops of 0..40 rounds" all_least

let t2 () =
  let ok s = match Kit.Json.parse s with Ok _ -> true | Error _ -> false in
  check "T2 object" (ok {| {"a": [1, -2, true, null, "xé\n"]} |});
  check "T2 surrogate pair" (Kit.Json.parse {|"😀"|} = Ok (J.String "\xf0\x9f\x98\x80"));
  check "T2 refuses a fraction" (not (ok "1.5"));
  check "T2 refuses trailing text" (not (ok "[1] 2"));
  check "T2 refuses a bad escape" (not (ok {|"\q"|}))

let round_trip_program p =
  match Kit.Json.parse (Kit.Json.render (Kit.Json.program_json p)) with
  | Ok j -> Kit.Json.program j = Some p
  | Error _ -> false

(* The fixture: one program a line (write.lean). *)
let read_file f = In_channel.with_open_bin f In_channel.input_all

let bytes_of_hex h =
  String.init (String.length h / 2) (fun i -> Char.chr (int_of_string ("0x" ^ String.sub h (2 * i) 2)))

type entry = { name : string; program : Kit.program option; verdict : string list; json : string }

let fixture () =
  String.split_on_char '\n' (read_file "verdicts.txt")
  |> List.filter_map (fun l ->
         match String.split_on_char '\t' l with
         | name :: hex :: rest when rest <> [] ->
           let json = List.nth rest (List.length rest - 1) in
           let verdict = List.filteri (fun i _ -> i < List.length rest - 1) rest in
           Some { name; program = Kit.program_of_bytes (bytes_of_hex hex); verdict; json }
         | _ -> None)

(* JSON up to the order of an object's keys *)
let rec sorted (j : J.t) : J.t =
  match j with
  | J.Object fields ->
    J.Object (List.sort (fun (a, _) (b, _) -> compare a b) (List.map (fun (k, v) -> (k, sorted v)) fields))
  | J.Array js -> J.Array (List.map sorted js)
  | j -> j

let t3 corpus =
  check "T3 doubling round trips" (round_trip_program doubling);
  check "T3 the self call round trips" (round_trip_program self_call);
  let rows_back =
    match Kit.Json.parse (Kit.Json.render (Kit.Json.rows_json [ echo ])) with
    | Ok j -> Kit.Json.rows j = Some [ echo ]
    | Error _ -> false
  in
  check "T3 a row table round trips" rows_back;
  let tape = [ unit_ok; Kit.fail (Val_str "boom"); Kit.succeed (Val_list [ Val_nat 3 ]) ] in
  let tape_back =
    match Kit.Json.parse (Kit.Json.render (J.Array (List.map Kit.Json.exit_json tape))) with
    | Ok j -> Kit.Json.exits j = Some tape
    | Error _ -> false
  in
  check "T3 a tape round trips" tape_back;
  let decoded = List.filter_map (fun e -> Option.map (fun p -> (e, p)) e.program) corpus in
  check "T3 every fixture program decodes" (List.length decoded = List.length corpus);
  let reads =
    List.filter (fun (e, p) -> match Kit.Json.parse e.json with
        | Ok j -> Kit.Json.program j = Some p | Error _ -> false) decoded in
  let prints =
    List.filter (fun (e, p) -> match Kit.Json.parse e.json with
        | Ok j -> sorted j = sorted (Kit.Json.program_json p) | Error _ -> false) decoded in
  Printf.printf "T3 fixture: %d programs; Lean's JSON reads back for %d; the kit prints Lean's JSON for %d\n"
    (List.length decoded) (List.length reads) (List.length prints);
  check "T3 Lean's JSON reads to the program" (List.length reads = List.length decoded);
  check "T3 the kit prints Lean's JSON" (List.length prints = List.length decoded)

let t4 () =
  let raw =
    let lt a b = Term_app ("lt", Terms_cons (a, Terms_cons (b, Terms_nil))) in
    let mul a b = Term_app ("mul", Terms_cons (a, Terms_cons (b, Terms_nil))) in
    Eff_iterate (None, A.nat 1, lt (Term_var 0) (A.nat 16), mul (Term_var 0) (A.nat 2), Term_var 0,
                 Eff_perform (NativeOp_external 0, Term_var 0))
  in
  check "T4 the doubling loop by name is the raw one" (doubling = raw);
  check "T4 an unbound row is refused by name" (A.build ~app (A.perform "nope" A.unit) = Error (A.Unbound_row "nope"));
  check "T4 an unbound definition is refused by name" (A.build ~app (A.call "nope" A.unit) = Error (A.Unbound_def "nope"));
  (match A.build_checked ~app doubling_src with
   | Ok (_, t) -> check "T4 doubling types at Effect<number, never>"
                    (Kit.ty_text t.answer = "number" && Kit.ty_text t.error = "never")
   | Error _ -> check "T4 doubling types" false)

let reason_head (r : Kit_gen.type_refusal) =
  match Kit.Json.refusal_json r with
  | J.Object fields ->
    (match List.assoc_opt "reason" fields with
     | Some (J.String s) -> s
     | Some (J.Object (("_tag", J.String s) :: _)) -> s
     | _ -> "?")
  | _ -> "?"

let path_text (r : Kit_gen.type_refusal) =
  if r.path = [] then "." else String.concat "." (List.map string_of_int r.path)

let t5 corpus =
  let empty = Kit.app () in
  let disagree =
    List.filter_map
      (fun e ->
        match e.program with
        | None -> Some (e.name ^ ": no decode")
        | Some p ->
          let ours = match Kit.check empty p with
            | Ok t -> [ "typed"; Kit.ty_text t.answer; Kit.ty_text t.error ]
            | Error r -> [ "refused"; reason_head r; path_text r ] in
          if ours = e.verdict then None
          else Some (Printf.sprintf "%s: %s, Lean %s" e.name (String.concat " " ours) (String.concat " " e.verdict)))
      corpus
  in
  Printf.printf "T5 fixture: %d programs, %d disagreements with Lean's verdicts\n" (List.length corpus)
    (List.length disagree);
  List.iteri (fun i d -> if i < 10 then Printf.printf "  %s\n" d) disagree;
  check "T5 the lowered checker is Lean's" (disagree = [])

