  check "T6 a wrong request type is refused" (match A.build_checked ~app wrong with Error (`Type _) -> true | _ -> false);
  check "T6 the right one types" (match A.build_checked ~app (A.perform "echo" (A.nat 1)) with Ok _ -> true | _ -> false)

let t7 () =
  let bad = [ unit_ok; Kit.succeed (Val_str "oops"); unit_ok; unit_ok ] in
  let guarded = Kit.Host.guarded app Kit.Host.tape in
  (match Kit.settle app guarded bad doubling with
   | Kit.Settled { run; _ } ->
     check "T7 the run waits at the refused reply" (run.stop = Kit.Stop_waiting (0, Val_nat 2));
     check "T7 the reason names the reply and the fault"
       (Kit.wait_reason app Kit.Host.tape run
        = Some (Kit.Refused (Kit.succeed (Val_str "oops"), Kit.ReplyFault_answerType Ty_unit)))
   | Kit.Unsettled _ -> check "T7 the run settles" false);
  let failing_row = A.row "lookup" ~request:Ty_nat ~answer:Ty_string ~error:Ty_string () in
  let app2 = Kit.app ~rows:[ failing_row ] () in
  let p = match A.build ~app:app2 (A.perform "lookup" (A.nat 1)) with Ok e -> e | Error _ -> assert false in
  (match Kit.settle app2 (Kit.Host.guarded app2 Kit.Host.tape) [ Kit.fail (Val_str "missing") ] p with
   | Kit.Settled { run; _ } ->
     check "T7 a failure in the error column is applied"
       (match run.stop with Kit.Stop_finished (Exit_failure _) -> true | _ -> false)
   | Kit.Unsettled _ -> check "T7 the failing run settles" false);
  let plain = Kit.settle app Kit.Host.tape (units 4) doubling in
  let checked = Kit.settle app guarded (units 4) doubling in
  check "T7 fitting replies: the guarded run is the run"
    (match plain, checked with
     | Kit.Settled a, Kit.Settled b -> a.budget = b.budget && Kit.calls a.run = Kit.calls b.run && a.run.stop = b.run.stop
     | _ -> false)

let t8 corpus =
  let agree_on name app host st p =
    match Kit.settle ~limit:256 app host st p with
    | Kit.Settled { run; _ } ->
      let m = Kit_machine.run app host st p in
      if Kit_machine.agree run m then `Agree else `Differ (name, run, m)
    | Kit.Unsettled _ -> `Unsettled
  in
  List.iter
    (fun (name, tape) ->
      check ("T8 the runners agree: " ^ name)
        (agree_on name app Kit.Host.tape tape doubling = `Agree))
    [ ("doubling, four replies", units 4); ("doubling, three replies", units 3) ];
  let cells =
    build A.(let* c = cell (nat 0) in
             loop ~init:(nat 1) ~test:(fun i -> i < nat 8) ~step:(fun i _ -> i * nat 2) ~result:(fun _ -> unit)
               (fun i -> set c i) >> get c) in
  check "T8 the runners agree: a cell written in a loop" (agree_on "cells" app Kit.Host.silent () cells = `Agree);
  let caught = build A.(catch (fail (str "boom")) (fun _ -> succeed (nat 7))) in
  check "T8 the runners agree: a caught failure" (agree_on "catch" app Kit.Host.silent () caught = `Agree);
  let empty = Kit.app () in
  let results =
    List.filter_map
      (fun e ->
        match e.program with
        | Some p when Kit.outside p = None ->
          Some (agree_on e.name empty Kit.Host.silent () p)
        | _ -> None)
      corpus
  in
  let count f = List.length (List.filter f results) in
  let differ = List.filter_map (function `Differ (n, _, _) -> Some n | _ -> None) results in
  Printf.printf "T8 fixture: %d programs in the fragment; %d agree, %d unsettled at 256, %d differ%s\n"
    (List.length results) (count (( = ) `Agree)) (count (( = ) `Unsettled)) (List.length differ)
    (if differ = [] then "" else ": " ^ String.concat " " (List.filteri (fun i _ -> i < 12) differ));
  check "T8 the runners agree on the fixture" (differ = [])

