    sum1 -> ('a1 * 'a2) -> (__ * ('a1 * 'a2)) option **)

let route cs rows e st =
  match e with
  | Inl1 c ->
    (match cs __ c (fst st) with
     | Some p -> let (x, s') = p in Some (x, (s', (snd st)))
     | None -> None)
  | Inr1 r ->
    (match rows __ r (snd st) with
     | Some p -> let (x, t') = p in Some (x, ((fst st), t'))
     | None -> None)

