(** val trace :
    ((__ storeE, __ rowE, __) sum1, 'a1) host -> ((__ storeE, __ rowE, __)
    sum1, Lane_eval.exitv option) program -> 'a1 -> (step list * stop) * 'a1 **)

let rec trace h p s =
  match p with
  | PRet r ->
    (match r with
     | Some ex -> (([], (Finished ex)), s)
     | None -> (([], Cut), s))
  | PVis (e, k) ->
    (match h __ e s with
     | Some p0 ->
       let (x, s') = p0 in
       let (p1, s'') = trace h (k x) s' in
       let (steps, st) = p1 in ((((step_of e x) :: steps), st), s'')
     | None -> (([], (stop_of e)), s))

