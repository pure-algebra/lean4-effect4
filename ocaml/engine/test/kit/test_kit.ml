(* test_kit.ml -- the native kit's lane.

   What it is: the kit's behaviours, checked on the examples the Rocq development checks
   (docs/research/2026-10-16-itrees/rocq/BudgetCheck.v) and on Lean's fixture verdicts.txt beside
   this file (GENERATED by write.lean, `make gen-fixtures`): the 408 programs of the printed
   corpus's sources, each with its canonical bytes, Lean's verdict and Lean's JSON print. The
   examples are written with Kit_author, which is Lean's authoring surface lowered.
   Depends on: Effect4_kit (Kit, Kit_author, Kit_serve), Effect4_gen.Api_gen, Eff_types, Eff_codec.

   Properties:
   T1  The one run (Kit.run): the doubling loop under a tape of four replies settles at budget 5,
       finished with 16 after four calls; under three it waits on row 0 with 8; a loop that is
       always true and calls nothing is unsettled at every limit tried; a definition that calls
       itself at once is unsettled too; each frame extends the one before; the budget a run
       settles at is the least one, every frame before it cut, on loops of 0 to 40 rounds.  tested
   T2  The JSON text parser is Lean's grammar, lowered (NatJson.parse, the one both session
       drivers read with): RFC 8259 JSON into the profile's tree. A number that is no plain
       natural (a sign, a fraction, an exponent, more than 16 digits) is a numeral, which Lean's
       reader refuses at its place; a key written twice reaches the reader, which refuses it at
       its object. It refuses a comment, an unquoted key, a control byte inside a string, a
       leading zero, trailing text, a bad escape, a lone surrogate, NaN and a tuple, each at its
       byte, and the controls pin the three where yojson's text was wider.  tested
   T3  JSON: a program, a row table and a tape print and read back to themselves. On the
       fixture, Lean's JSON print reads to the program its bytes decode to, and the kit prints
       Lean's JSON, up to the order of an object's keys (Lean's printer sorts them).  tested
   T4  Authoring through Lean's surface: the doubling loop built by name is the raw one; an
       unbound row and an unbound definition are refused by name at the call's node, and a row
       declared twice is refused; the built doubling types at Effect<number, never>.  tested
   T5  The lowered checker is Lean's: on every fixture program it types where Lean types, with
       Lean's answer and error spellings, and refuses where Lean refuses, with Lean's reason and
       address.                                                             tested
   T6  Red control: a program with a wrong request type is refused by the checker, and the same
       program with the right one types, so T4 and T5 compare verdicts that differ.  tested
   T7  Reply admission: a reply that is no member of its row's answer type is not applied, so the
       run stops refused at that call, with the reply and the fault, and the machine refuses it
       too; a failure inside the row's error column is applied.             tested
   T8  The two runners agree: on the examples under their tapes, and on every fixture program in
       the tree's fragment, typed or not, generators among them, the tree's settled run and the
       machine's run finish or wait alike, with the same host calls; a program outside the
       fragment runs on the machine.                                        tested
   T9  Admission: a host row registered `deferred` is refused at admission, at its index, though
       the program types; the same row registered `external` is admitted.  tested
   T10 The JSON lines protocol (Kit_serve S3): `run` answers the tree's run with the machine's
       agreement and its frames when asked, an unreadable program is an error, a forked program
       runs on the machine, and `explore` of it answers the address outside the tree.
                                                                            tested
   T11 Exploration: the replies drawn from a row's types fit its row; a program that branches on
       a list's length has a path for each branch and for each failure of its error column; each
       path's tape replays the path on the machine.                         tested
   T12 Ingress (Kit B7, M2): the review's A1.1 reply (`NegInt max_int`, -2^62, at an `int` row)
       is not applied, on the tape route with and without the machine's cross-check and on a
       native host: the run stops refused at that call, Lean's profile support naming the
       negative integer at its path in the reply's value tree; the machine refuses it too. Red
       control: the reply -2 finishes with 1, as Lean answers. A program that states a literal
       outside the profile is unsupported at its node, and neither runner starts; the largest
       literal inside runs. A reply that is no Lean value (a natural below zero) is refused as
       not a value; the largest natural inside the profile is applied.       tested
   T13 The command line's numeric options (Kit_serve S4, the review's A5.2): a negative, a
       malformed, an empty, a fractional, a hexadecimal and an overflowing value are input
       errors for `--limit`, `--budget` and `--width`; zero and five read.  tested *)

