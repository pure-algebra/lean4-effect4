let unit_ok : Kit.exit = Kit.succeed Val.Unit
let units n = List.init n (fun _ -> unit_ok)
let echo = A.row "echo" ~request:Ty.Nat ~answer:Ty.Unit ()
let app = Kit.app ~rows:[ echo ] ()

(* the doubling loop of Examples.v, by name *)
let doubling_src =
  A.loop
    ~init:(A.nat 1)
    ~test:(fun c -> A.(c < nat 16))
    ~step:(fun c _ -> A.(c * nat 2))
    ~result:(fun c -> c)
    (fun c -> A.perform "echo" c)
;;

let build_in app ?defs p =
  match A.build ~app ?defs p with
  | Ok e -> e
  | Error r -> failwith (A.refusal_text r)
;;

let build ?defs p = build_in app ?defs p
let doubling = build doubling_src

let forever =
  build
    (A.loop
       ~init:(A.nat 0)
       ~test:(fun _ -> A.bool true)
       ~step:(fun c _ -> c)
       ~result:(fun _ -> A.unit)
       (fun _ -> A.succeed A.unit))
;;

let self_call =
  build
    ~defs:[ A.def "f" ~request:Ty.Nat ~answer:Ty.Nat (fun r -> A.call "f" r) ]
    (A.call "f" (A.nat 0))
;;

let stop_text : Kit.stop -> string = function
  | Kit.Finished (Exit.Success (Val.Nat n)) -> "finished " ^ Z.to_string n
  | Kit.Finished _ -> "finished other"
  | Kit.Unsettled -> "unsettled"
  | Kit.Waiting (i, Val.Nat n) ->
    Printf.sprintf "waiting %s %s" (Z.to_string i) (Z.to_string n)
  | Kit.Waiting (i, _) -> "waiting " ^ Z.to_string i
  | Kit.Refused (i, _, _, _) -> "refused " ^ Z.to_string i
  | Kit.Unsupported _ -> "unsupported"
  | Kit.Stopped why -> "stopped " ^ why
;;

let report_text (r : 's Kit.report) =
  Printf.sprintf
    "%s %s %d"
    (match r.budget with
     | Some k -> string_of_int k
     | None -> "-")
    (stop_text r.trace.stop)
    (List.length (Kit.calls r.trace))
;;

let t1 () =
  check
    "T1 doubling settles at 5 with 16, four calls"
    (report_text (Kit.run app Kit.Reactor.tape (units 4) doubling) = "5 finished 16 4");
  check
    "T1 three replies: waiting on row 0 with 8"
    (report_text (Kit.run app Kit.Reactor.tape (units 3) doubling) = "4 waiting 0 8 3");
  check
    "T1 the silent loop is unsettled"
    (report_text (Kit.run ~limit:200 app Kit.Reactor.silent () forever) = "- unsettled 0");
  check
    "T1 the self call is unsettled"
    (report_text (Kit.run ~limit:64 app Kit.Reactor.silent () self_call) = "- unsettled 0");
  let r = Kit.run ~frames:true app Kit.Reactor.tape (units 4) doubling in
  let rec prefix a b =
    match a, b with
    | [], _ -> true
    | x :: a, y :: b -> x = y && prefix a b
    | _ -> false
  in
  let rec grows = function
    | f :: (g :: _ as rest) -> prefix (Kit.calls f) (Kit.calls g) && grows rest
    | _ -> true
  in
  check "T1 frames grow, budgets 0 to 5" (grows r.frames && List.length r.frames = 6);
  let counter m =
    build
      (A.loop
         ~init:(A.nat 0)
         ~test:(fun c -> A.(c < nat m))
         ~step:(fun c _ -> A.atom "succ" [ c ])
         ~result:(fun c -> c)
         (fun c -> A.perform "echo" c))
  in
  let least m =
    let r =
      Kit.run
        ~limit:200
        ~frames:true
        ~check:false
        app
        Kit.Reactor.tape
        (units m)
        (counter m)
    in
    match r.budget, List.rev r.frames with
    | Some k, last :: before ->
      List.length r.frames = k + 1
      && last.stop <> Kit.Unsettled
      && List.for_all (fun (f : Kit.trace) -> f.stop = Kit.Unsettled) before
    | _ -> false
  in
  check
    "T1 the settled budget is the least, loops of 0..40 rounds"
    (List.for_all least (List.init 41 Fun.id))
;;

let t2 () =
  let ok s =
    match Kit.Json.parse s with
    | Ok _ -> true
    | Error _ -> false
  in
  check "T2 object" (ok {| {"a": [1, -2, true, null, "xé\n"]} |});
  check
    "T2 surrogate pair"
    (Kit.Json.parse {|"😀"|} = Ok (J.NatJson_str "\xf0\x9f\x98\x80"));
  check "T2 a fraction is a numeral" (Kit.Json.parse "1.5" = Ok (J.NatJson_numeral "1.5"));
  check
    "T2 the reader refuses a numeral at its place"
    (match
       Kit.Json.read { G.root = G.Shape_nat; defs = [] } (J.NatJson_numeral "1.5")
     with
     | Error
         { Located.site = G.JsonSite_value []
         ; reason = G.JsonReason_expected G.Shape_nat
         } -> true
     | _ -> false);
  check "T2 refuses trailing text" (not (ok "[1] 2"));
  check "T2 refuses a bad escape" (not (ok {|"\q"|}));
  check "T2 refuses a leading zero" (not (ok "007"));
  check "T2 refuses a lone surrogate" (not (ok {|"\ud800"|}));
  check "T2 refuses NaN" (not (ok "NaN"));
  check "T2 refuses a yojson tuple" (not (ok "(1, 2)"));
  (* The numbers the tree does not hold as naturals, each refused by the reader at its place. *)
  let nat_doc = { G.root = G.Shape_nat; defs = [] } in
  let reads_as text reason =
    match Kit.Json.parse text with
    | Ok j ->
      (match Kit.Json.read nat_doc j with
       | Error { Located.site = G.JsonSite_value []; reason = r } -> r = reason
       | _ -> false)
    | Error _ -> false
  in
  check "T2 -0 is a numeral, refused" (reads_as "-0" (G.JsonReason_expected G.Shape_nat));
  check
    "T2 1e0 is a numeral, refused"
    (reads_as "1e0" (G.JsonReason_expected G.Shape_nat));
  check
    "T2 a natural past the int range is a numeral, refused as outside the profile"
    (reads_as
       "4611686018427387904"
       (G.JsonReason_naturalOutsideProfile (Z.of_int 9007199254740991)));
  check
    "T2 2^53 reads as a natural, refused as outside the profile"
    (reads_as
       "9007199254740992"
       (G.JsonReason_naturalOutsideProfile (Z.of_int 9007199254740991)));
  (* A key written twice is refused at its object, by the reader, not by the text parser. *)
  let pair_doc =
    { G.root = G.Shape_struct ("P", [ "a", G.Shape_nat; "b", G.Shape_nat ]); defs = [] }
  in
  check
    "T2 a key written twice is refused at its object"
    (match Kit.Json.parse {|{"a":1,"b":2,"a":3}|} with
     | Ok j ->
       (match Kit.Json.read pair_doc j with
        | Error
            { Located.site = G.JsonSite_value []
            ; reason = G.JsonReason_duplicateField "a"
            } -> true
        | _ -> false)
     | Error _ -> false);
  (* Controls: where yojson's text was wider than RFC 8259, Lean's grammar refuses, at the byte. *)
  check
    "T2 control: a comment is refused at its byte"
    (Kit.Json.parse "/* c */ 1 // d" = Error "JSON text at byte 0: expected a value");
  check
    "T2 control: an unquoted key is refused at its byte"
    (Kit.Json.parse "{a:1}"
     = Error "JSON text at byte 1: expected an object's key, a string");
  check
    "T2 control: a control byte inside a string is refused at its byte"
    (Kit.Json.parse "\"a\tb\""
     = Error "JSON text at byte 2: expected no control byte inside a string")
;;

let round_trip_program p =
  match Kit.Json.parse (Kit.Json.render (Kit.Json.program_json p)) with
  | Ok j -> Kit.Json.program j = Some p
  | Error _ -> false
;;

(* The fixture: one program a line (write.lean). *)
let read_file f = In_channel.with_open_bin f In_channel.input_all

let bytes_of_hex h =
  String.init
    (String.length h / 2)
    (fun i -> Char.chr (int_of_string ("0x" ^ String.sub h (2 * i) 2)))
;;

type entry =
  { name : string
  ; program : Kit.program option
  ; verdict : string list
  ; json : string
  }

let fixture () =
  String.split_on_char '\n' (read_file "verdicts.txt")
  |> List.filter_map (fun l ->
    match String.split_on_char '\t' l with
    | name :: hex :: rest when rest <> [] ->
      let json = List.nth rest (List.length rest - 1) in
      let verdict = List.filteri (fun i _ -> i < List.length rest - 1) rest in
      Some { name; program = Kit.program_of_bytes (bytes_of_hex hex); verdict; json }
    | _ -> None)
;;

(* JSON up to the order of an object's keys *)
let rec sorted (j : J.t) : J.t =
  match j with
  | J.NatJson_obj fields ->
    J.NatJson_obj
      (List.sort
         (fun (a, _) (b, _) -> compare a b)
         (List.map (fun (k, v) -> k, sorted v) fields))
  | J.NatJson_arr js -> J.NatJson_arr (List.map sorted js)
  | j -> j
;;

