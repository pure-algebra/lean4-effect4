#!/usr/bin/env bash
# tools/lean-flags.sh — write link/c_flags.sexp and link/lean_flags.sexp for dune.
#
# Both files are GENERATED (this script is the rule); they carry absolute Linux paths of
# this machine and are not meant to be shared. lean_flags.sexp embeds a digest of
# Bridge.o, so a recompiled Bridge.o changes the file and dune relinks everything.
#
# The recipe is build-link.sh's: gcc + the system glibc, Lean's static libraries and its
# bundled static libc++ / libc++abi / libunwind / gmp / uv named explicitly (`-lc++` would
# resolve to a shared libc++ the system lacks; leanc as the driver links old-glibc stubs
# that clash with OCaml's libasmrun). The archives sit in one --start-group so their
# order cannot matter. They are `link_flags` of the executables (`-cclib` pairs), not
# `c_library_flags` of the library: the library's flags would also go into the bytecode
# stubs .so, and libleanrt's local-exec TLS cannot be linked into a shared object.
set -euo pipefail
source "$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)/lean-env.sh"
[ -f "$E4_OUT/Bridge.o" ] || { echo "no $E4_OUT/Bridge.o: run tools/compile-bridge.sh first" >&2; exit 1; }
libs=()
for lib in $(e4_lean_libs); do
  [ -f "$lib" ] || { echo "MISSING $lib" >&2; exit 1; }
  libs+=("$lib")
done
digest=$(sha256sum "$E4_OUT/Bridge.o" | cut -c1-16)
{
  echo "; GENERATED by tools/lean-flags.sh — do not edit; rerun the script to regenerate."
  echo "; Bridge.o sha256 $digest (this line changes when Bridge.o does, so dune relinks)."
  echo "(-cclib \"$E4_OUT/Bridge.o\""
  echo " -cclib -Wl,--start-group"
  for lib in "${libs[@]}"; do echo " -cclib \"$lib\""; done
  echo " -cclib \"-L$E4_LEAN_PREFIX/lib/lean\" -cclib \"-L$E4_LEAN_PREFIX/lib\""
  for l in -lStd -lInit -lleanrt -l:libc++.a -l:libc++abi.a -l:libunwind.a -l:libgmp.a -l:libuv.a; do
    echo " -cclib $l"
  done
  echo " -cclib -Wl,--end-group"
  echo " -cclib -lpthread -cclib -ldl -cclib -lm)"
} > "$E4_LINK_DIR/lean_flags.sexp"
{
  echo "; GENERATED by tools/lean-flags.sh — do not edit; rerun the script to regenerate."
  echo "(\"-I$E4_LEAN_PREFIX/include\")"
} > "$E4_LINK_DIR/c_flags.sexp"
echo "--- wrote $E4_LINK_DIR/lean_flags.sexp (Bridge.o $digest, ${#libs[@]} Lean libraries) and c_flags.sexp"
