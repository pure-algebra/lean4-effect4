#!/usr/bin/env python3
"""The diff half of `render-deep.sh`, as a file: compare (or, with `--write`, replace) the
generated carrier block of an avatar module with a rendering of `OCaml5.Ml.Deep.*`.

    render-diff.py <deep_stores.ml> <stores.gen.ml> [--write]

`render-deep.sh` embeds this as a heredoc and runs the renderer through `lake env lean --run`,
which on this checkout cannot see the OCaml5 oleans (they are built into a scratch directory,
not `.lake/build`); `tools/render-deep-win.ps1` runs the renderer with `-M4096` and calls this.
"""
import difflib
import sys

target, gen = sys.argv[1], sys.argv[2]
write = len(sys.argv) > 3 and sys.argv[3] == "--write"
text = open(target, encoding="utf-8", newline="").read()
start = text.index("(* Generated by OCaml5.Ml (`Render.lean`, seat W1)")
stop = text.index("(* ===== END GENERATED =====")
have = text[start:stop]
want = open(gen, encoding="utf-8", newline="").read().replace("\r\n", "\n")
if have.rstrip() == want.rstrip():
    print(f"{target}: carriers IDENTICAL to OCaml5.Ml.Deep")
elif write:
    open(target, "w", encoding="utf-8", newline="").write(text[:start] + want.rstrip() + "\n\n" + text[stop:])
    print(f"{target}: carriers REWRITTEN from OCaml5.Ml.Deep")
else:
    print(f"{target}: carriers DIFFER")
    for line in difflib.unified_diff(have.splitlines(), want.splitlines(), "avatar", "generated", lineterm=""):
        print("    " + line)
    raise SystemExit(1)
