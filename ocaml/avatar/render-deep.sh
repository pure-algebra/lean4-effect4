#!/usr/bin/env bash
# Seat W1: render one avatar module's carriers from `OCaml5.Ml.Deep.*` and diff them against
# the block the avatar file carries. The diff is against the real file, not a copy, so the
# claim decays the moment either side changes -- which is the point (P5 §11).
#
#   render-deep.sh stores      # deep_stores.ml
#
# With `--write`, the rendered block replaces the one in the file.
set -euo pipefail
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
# <repo>/ocaml/avatar -> <repo>. The estate lived under `workshop/OCaml5/` until 2026-09-04.
repo=$(CDPATH= cd -- "$here/../.." && pwd)
out=${W1_BUILD:-${TMPDIR:-/tmp}/effect4-render-deep}
mkdir -p "$out"
which=${1:-stores}
write=${2:-}

# Seat F2: `lake env` resolves the manifest first, and the manifest pins lean4-typescript
# v0.5.0 at a commit that exists only on the PC (never pushed), so on a checkout without it
# `lake env lean` dies before running anything. Fall back to `lean` over the built oleans
# (`.lake/build/lib/lean` and the packages' build libs), which is what `lake env` would have
# set up; `OCaml5.Render` itself is rebuilt the same way (see the F2 report, open question).
lean_run() {
  if ( cd "$repo" && lake env true ) > /dev/null 2>&1; then
    ( cd "$repo" && lake env lean --run src/OCaml5/Tools/RenderDeep.lean "$@" )
  else
    ( cd "$repo" && \
      LEAN_PATH=.lake/build/lib/lean:.lake/packages/effects/.lake/build/lib/lean:.lake/packages/hash/.lake/build/lib/lean:.lake/packages/typescript/.lake/build/lib/lean \
      lean --run src/OCaml5/Tools/RenderDeep.lean "$@" )
  fi
}
lean_run "$which" > "$out/$which.gen.ml"

file="$here/deep_$which.ml"
begin='(* Generated by OCaml5.Ml (`Render.lean`, seat W1)'
end='(* ===== END GENERATED ====='
python3 - "$file" "$out/$which.gen.ml" "${write:-}" <<'PY'
import sys
target, gen, write = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(target).read()
start = text.index("(* Generated by OCaml5.Ml (`Render.lean`, seat W1)")
stop = text.index("(* ===== END GENERATED =====")
have = text[start:stop]
want = open(gen).read()
if have.rstrip() == want.rstrip():
    print(f"{target}: carriers IDENTICAL to OCaml5.Ml.Deep")
elif write == "--write":
    open(target, "w").write(text[:start] + want.rstrip() + "\n\n" + text[stop:])
    print(f"{target}: carriers REWRITTEN from OCaml5.Ml.Deep")
else:
    import difflib
    print(f"{target}: carriers DIFFER")
    for line in difflib.unified_diff(have.splitlines(), want.splitlines(),
                                     "avatar", "generated", lineterm=""):
        print("    " + line)
    raise SystemExit(1)
PY
