(* `Prim.ofExit exit` as a program: the avatar's return/`raise` pair. This is what
   `DeferredStore.complete` stores for `deferredInterruptWith` (`Stores.lean:1220-1223`) and,
   through `completion_prim`, for every `Completion.ofExit`. *)
let prim_of_exit (e : exitv) : program =
  match e with
  | Esuccess v -> fun () -> v
  | Efailure cause -> fun () -> raise (Einterrupt_exn cause)

(* `completionPrim` (`Stores.lean:1081-1085`): the stored primitive a `Completion` names --
   `done exit = completeWith (Prim.ofExit exit)` (`completionPrim_ofExit`, `:1433`). The
   `ofRefGet` arm is `Prim.sync (Thunk.op (SyncOp.refGet cell))`, an effect stored and not
   run; the avatar's awaiting arms run the stored program on the *arm's* stack for its exit
   (the fixture's rows need it there), where a `sync` cannot be performed, so that arm still
   refuses by name when run (report row W1-2; no program of the avatar's alphabets stores
   one). *)
let completion_prim (c : completion) : program =
  match c with
  | CoofExit exit_ -> prim_of_exit exit_
  | CoofRefGet _cell -> fun () -> refuse "Effect4.Deep.completionPrim (Completion.ofRefGet)"

(* `finProgram` (`Stores.lean:1036`): the program a scope finalizer *name* runs
   (`internal/effect.ts:4021`). All five arms ported (seat F1): `interruptFiber` by its
   `skipSelf` flag is `interruptScoped`/`interrupt` on the fiber id; `closeChildScope` is
   `closeScope`, whose program the arm installs and the wrapper runs; `parkThen` is a
   `Prim.async` at an external slot, i.e. a park the tape's `answerAsync` resumes. *)
let fin_program (fin : fin_name) (exit_ : exitv) : program =
  match fin with
  | FininterruptFiber (fiber, true) -> fun () -> Effect.perform (Op_interrupt_scoped fiber)
  | FininterruptFiber (fiber, false) -> fun () -> Effect.perform (Op_interrupt_fiber fiber)
  | FincloseChildScope scope ->
    fun () ->
      ignore (Effect.perform (Op_close_scope (scope, exit_)));
      take_current_program () ()
  | FindetachFromParent (parent, key) ->
    fun () -> Effect.perform (Op_store (Rsync (SscopeRemove (parent, key))))
  | Finrelease (label, fails) ->
    fun () -> if fails then raise (Efail_exn label) else Vunit
  | FinparkThen _slot -> fun () -> Effect.perform (Op_never ())
  (* `57924eb` (R2-7): `awaitAllChildren`'s finalizer (`:5319-5333`) -- await the children
     added since the snapshot, on any exit, under the finalizer mask; the wire arm takes the
     snapshot as handles. *)
  | FinawaitNewChildren snapshot ->
    fun () ->
      Effect.perform
        (Op_await_new_children (Vlist (List.map (fun id -> Vhandle (handle_index "fiber" id)) snapshot)))

(* The exit of a program run on this stack: `Prim.exitFrame` (`Runtime.lean`), the avatar's
   `try`. A typed failure and a delivered cause are both `Exit.failure`. *)
let exit_of_run (program : program) : exitv =
  try Esuccess (program ()) with
  | Efail_exn code -> Efailure (cause_fail code)
  | Einterrupt_exn c -> Efailure c

(* `Prim.ofExit` on this stack: return the value or re-raise the cause. *)
let deliver_exit (e : exitv) : value =
  match e with Esuccess v -> v | Efailure c -> raise (Einterrupt_exn c)

(* `Prim.onExit body finalizer flag` (`Runtime.lean:125`) on this stack: the body's exit is
   taken (`exit_of_run`), the frame's `contAll` masks the fiber and names the finalizer
   (`Op_on_exit_enter`, one iteration, as `finalizerOr` is), the finalizer program runs,
   the restoring `setInterruptible true` frame is passed (`Op_set_interruptible`, which
   delivers a cause recorded meanwhile, M2), and the original exit is restored
   (`restoreName`) or the finalizer's failure merged over it (`mergeName`,
   `Runtime.lean:874-880`). Seat F1. *)
let on_exit_program (body : program) (fin_name_str : string) (finalizer : exitv -> program)
    (fin_interruptible : bool) : program =
 fun () ->
  let exit_ = exit_of_run body in
  let previous = Effect.perform (Op_on_exit_enter (fin_name_str, exit_, fin_interruptible)) in
  let fin_exit = exit_of_run (finalizer exit_) in
  (match previous with
   | Vbool true when not fin_interruptible ->
     ignore (Effect.perform (Op_set_interruptible true))
   | _ -> ());
  match fin_exit with
  | Esuccess _ -> deliver_exit exit_
  | Efailure c ->
    deliver_exit
      (match exit_ with
       | Esuccess _ -> Efailure c
       | Efailure previous -> Efailure (cause_combine previous c))

(* The `WithFiberAction.setInterruptible body flag` region (`Fibers.lean:930-937`, M2) on
   this stack: set the flag, run the body, restore the previous flag through the same arm,
   which delivers a cause recorded meanwhile when interruptibility returns. *)
let masked_region (flag : bool) (body : program) : program =
 fun () ->
  let previous =
    match Effect.perform (Op_set_interruptible flag) with Vbool b -> b | _ -> true
  in
  let exit_ = exit_of_run body in
  ignore (Effect.perform (Op_set_interruptible previous));
  deliver_exit exit_

(* The name a finalizer program carries in the `finalizerProgram` event
   (`RunEvent.finalizerProgram`'s `ν` is `Name.finalizerName fin`). *)
let fin_name_string : fin_name -> string = function
  | FininterruptFiber (fiber, skip) -> Printf.sprintf "interruptFiber(%d,%b)" fiber skip
  | FincloseChildScope scope -> Printf.sprintf "closeChildScope(%d)" scope
  | FindetachFromParent (parent, key) -> Printf.sprintf "detachFromParent(%d,%d)" parent key
  | Finrelease (label, fails) -> Printf.sprintf "release(%d,%b)" label fails
  | FinparkThen slot -> Printf.sprintf "parkThen(%d)" slot
  | FinawaitNewChildren snapshot ->
    Printf.sprintf "awaitNewChildren([%s])" (String.concat ";" (List.map string_of_int snapshot))

(* `progOf` (`Stores.lean:1057`), the interpretation of the declared program names, arm for
   arm. Every arm is ported (seat F1): the forks over a `ProgName` go through the Lean
   alphabet's own effects (`Op_fork_prog`, `Op_fork_in`, `Op_fork_scoped`, `Op_run_in`,
   `Op_race_all_prog`, `Op_close_scope`), `onExitOf` is `on_exit_program`, and
   `intoDeferred`/`intoBody` are the mask region around an `exitFrame`. The answer of a
   fork is the child's wire handle (report row W1-1: `Val.fiber` is `Vhandle`). *)
let rec prog_of (p : prog_name) : program =
  match p with
  | Pvalue v -> fun () -> v
  | PfailCause cause -> fun () -> raise (Einterrupt_exn cause)
  | PsyncOp op -> fun () -> Effect.perform (Op_store (Rsync op))
  | PyieldNow priority -> fun () -> Effect.perform (Op_yield_now priority)
  | Ppark _slot -> fun () -> Effect.perform (Op_never ())
  | PawaitDeferred cell -> fun () -> Effect.perform (Op_store (Rawait_deferred cell))
  | PintoDeferred (body, cell) ->
    (* `uninterruptibleMask(restore => …)` (`Deferred.ts:1778`), M2 *)
    masked_region false (prog_of (PintoBody (body, cell)))
  | PintoBody (body, cell) ->
    (* `flatMap(exit(restore(self)), exit => done(deferred, exit))` (`Deferred.ts:1779-1782`) *)
    fun () ->
      let exit_ = exit_of_run (masked_region true (prog_of body)) in
      Effect.perform (Op_store (Rsync (SdeferredCompleteWith (cell, CoofExit exit_))))
  | PmaskedPark slot -> masked_region false (prog_of (Ppark slot))
  | PawaitFibers targets ->
    fun () -> exits_val (Effect.perform (Op_await_fibers targets))
  | PfinalizerOf (fin, exit_) -> fin_program fin exit_
  | PinterruptDeferred cell ->
    fun () -> Effect.perform (Op_store (Rinterrupt_deferred cell))
  | PonExitOf (body, fin, flag) ->
    on_exit_program (prog_of body) (fin_name_string fin) (fin_program fin) flag
  | PseqOf (first, second) ->
    fun () ->
      ignore (prog_of first ());
      prog_of second ()
  | PforkThen (child, options, mode) ->
    fun () ->
      let handle = Effect.perform (Op_fork_prog (prog_of child, options)) in
      Effect.perform (Op_join_on (handle_target "fiber" (match handle with Vhandle h -> h | _ -> -1), mode))
  | PforkOnly (child, options) -> fun () -> Effect.perform (Op_fork_prog (prog_of child, options))
  | PforkInScope (child, options, scope, key) ->
    fun () -> Effect.perform (Op_fork_in (prog_of child, options, scope, key))
  | PrunInScope (target, scope, key) ->
    fun () -> Effect.perform (Op_run_in (target, scope, key))
  | PforkScopedOf (child, options, key) ->
    fun () -> Effect.perform (Op_fork_scoped (prog_of child, options, key))
  | PraceOf race ->
    fun () -> race_all_program (List.map prog_of (race_entrants race))
  | PcloseScopeOf (scope, exit_) ->
    fun () ->
      ignore (Effect.perform (Op_close_scope (scope, exit_)));
      take_current_program () ()
  | PawaitAllNew body ->
    (* `Stores.lean` (`57924eb`, R2-7): `snapshotThen body` is `onExit(self, _ => asVoid(
       fiberAwaitAll(new children)))` (`:5314-5333`) -- the await is the finalizer program
       `FinName.awaitNewChildren snapshot`, run on any exit under the finalizer mask, and
       the body's own value is answered. *)
    fun () ->
      let snapshot =
        match Effect.perform (Op_snapshot_children ()) with
        | Vlist items -> List.filter_map (function Vhandle h -> Some (handle_target "fiber" h) | _ -> None) items
        | _ -> []
      in
      on_exit_program (prog_of body) (fin_name_string (FinawaitNewChildren snapshot))
        (fin_program (FinawaitNewChildren snapshot)) false ()
  (* `Stores.lean:1130-1131` (`2f77f7d`): `fiberInterruptAll(targets)` (`:889-896`), the
     settled race's cleanup half (R2-12); `fiberJoin`/`fiberAwait` on an existing handle. *)
  | PinterruptFibers targets -> fun () -> Effect.perform (Op_interrupt_fibers targets)
  | PjoinFiber (target, mode) -> fun () -> Effect.perform (Op_join_on (target, mode))

(* `raceSettleProgram` (`Stores.lean:1134-1142`, R2-12) is `Deep_fibers.race_settle_program`:
   the machine resumes the host with it (`Aprogram`), so it lives beside the machine. *)
let race_settle_program = race_settle_program

(* `cancelProgram` (`Stores.lean:1107`): the cancel effect a cancel *name* runs. `cancelName`
   attached the parked fiber's identity and its resume token, so `_await`'s cleanup splices
   exactly that resume out. *)
let cancel_program (n : name) : program =
  match n with
  | NwithWaiter (NcancelAwait cell, waiter, token) ->
    fun () -> Effect.perform (Op_store (Rsync (SdeferredAwaitCleanup (cell, waiter, token))))
  (* `2f77f7d`: a fiber-observer park's cleanup drops the observers of that token (R2-3); a
     race park's cleanup interrupts the race's live entrants (R2-13). The machine runs the
     same two from the park closures (`Deep_fibers.drop_observers`, `cancel_race`). *)
  | NwithWaiter (NcancelPark, _, token) -> fun () -> Effect.perform (Op_drop_observers token)
  | NwithWaiter (NcancelRace race, _, _) -> fun () -> Effect.perform (Op_cancel_race race)
  | _ -> fun () -> Vunit

(* `closeSeqChain` (`Stores.lean:1115`): the finalizers in `closeOrder`, each awaited through
   its own exit, with the captured reasons merged by `exitAsVoidAll` at the end. Lean builds
   a `Prim` chain of `onSuccessAndFailure` frames; the avatar's chain is the OCaml `try`, so
   the recursion is a loop and `Name.closeSeq` is the loop's accumulator rather than a name. *)
let rec close_seq_chain (fins : fin_name list) (exit_ : exitv) (captured : reason list) :
    program =
  match fins with
  | [] -> fun () -> ( match void_all_of captured with
                      | Esuccess v -> v
                      | Efailure c -> raise (Einterrupt_exn c))
  | fin :: rest ->
    fun () ->
      let captured =
        try
          ignore (fin_program fin exit_ ());
          captured
        with
        | Efail_exn code -> captured @ [ Rfail code ]
        | Einterrupt_exn c -> captured @ c.reasons
      in
      close_seq_chain rest exit_ captured ()

(* `closeParChain` (`Stores.lean:1126`; `internal/effect.ts:3819-3826`): each finalizer is
   forked as an *immediate daemon* whose mask is the closing fiber's, then all of them are
   awaited together and every exit merged (`Name.mergeAwaitedExits`, M6: the merge reads
   the exits the countdown collected -- `Op_await_fibers` answers them as exits, so the
   reasons survive). Seat F1. *)
let rec close_par_chain (closer_interruptible : bool) (fins : fin_name list) (exit_ : exitv)
    (forked : int list) : program =
  match fins with
  | [] ->
    fun () ->
      let exits = Effect.perform (Op_await_fibers forked) in
      deliver_exit (merge_exits exits)
  | fin :: rest ->
    fun () ->
      let handle =
        Effect.perform
          (Op_fork_prog
             ( fin_program fin exit_,
               { start_immediately = true;
                 daemon = true;
                 mask_mode = (if closer_interruptible then Minterruptible else Muninterruptible) } ))
      in
      let child = match handle with Vhandle h -> handle_target "fiber" h | _ -> -1 in
      close_par_chain closer_interruptible rest exit_ (forked @ [ child ]) ()

(* `storesCloseScope` (`Stores.lean:1143`): `Effect4.Scope.closeState` runs first, so the
   state is written before any finalizer program is built, and the close of an already
   closed scope is void. `None` is an unknown scope key, which the machine turns into
   `Stuck.unknownScope` (M7). *)
let stores_close_scope (scope : int) (exit_ : exitv) (closer_interruptible : bool)
    (state : stores) : program option =
  match scope_store_entry_at state.scopes scope with
  | None -> None
  | Some entry ->
    if scope_is_closed entry.scope then Some (fun () -> Vunit)
    else begin
      let order = scope_close_order entry.scope in
      let strategy = entry.scope.strategy in
      scope_store_close_state state.scopes scope exit_;
      match strategy with
      | Fssequential -> Some (close_seq_chain order exit_ [])
      | Fsparallel -> Some (close_par_chain closer_interruptible order exit_ [])
    end

(* --------------------------------------------------- the store steps under `Prim.sync` *)

(* `syncOpStep` (`Stores.lean:1160`): every `sync` thunk that reads or writes the service
   state. `None` falls back to the pure `syncValue`. The store is written in place, so the
   Lean pair `(Stores × Val)` is the `Val` alone. *)
let sync_op_step (op : sync_op) (st : stores) : value option =
  match op with
  | SdeferredMake ->
    let key = deferred_store_make st.deferreds in
    Some (Vhandle key.index)
  | SdeferredIsDone cell ->
    Option.map (fun flag -> Vbool flag) (deferred_store_is_done st.deferreds cell)
  | SdeferredPoll cell ->
    Option.map (fun slot -> Vbool (slot <> None)) (deferred_store_poll st.deferreds cell)
  | SdeferredCompleteWith (cell, completion) ->
    (* `Stores.lean:1217-1219`: the store receives `completionPrim completion` *)
    Some (Vbool (deferred_store_complete st.deferreds cell (completion_prim completion)))
  | SdeferredInterruptWith (cell, interruptor) ->
    (* `Stores.lean:1220-1224`: `Prim.ofExit (Exit.failure (Cause.interrupt (some interruptor)))` *)
    Some
      (Vbool
         (deferred_store_complete st.deferreds cell
            (prim_of_exit (Efailure (cause_interrupt (Some interruptor))))))
  | SdeferredAwaitCleanup (cell, waiter, token) ->
    deferred_store_cancel st.deferreds cell waiter token;
    Some Vunit
  | SscopeMake strategy ->
    let key = st.next_name in
    scope_store_make st.scopes key strategy;
    st.next_name <- key + 1;
    Some (Vhandle key)
  | SscopeAdd (scope, key, finalizer) ->
    ignore (scope_store_add_finalizer st.scopes scope key finalizer);
    Some Vunit
  | SscopeRemove (scope, key) ->
    scope_store_remove_finalizer st.scopes scope key;
    Some Vunit
  | SscopeIsClosed scope ->
    Option.map (fun (entry : scope_entry) -> Vbool (scope_is_closed entry.scope))
      (scope_store_entry_at st.scopes scope)
  | op ->
    Option.map
      (fun (v, refs) ->
        st.refs <- refs;
        v)
      (ref_step op st.refs)

