let add_state (state : scope_state) (key : int) (finalizer : fin_name) : scope_state =
  match state with
  | Ssempty -> SsopenInline (key, finalizer)
  | SsopenEmpty -> SsopenInline (key, finalizer)
  | SsopenInline (existing_key, existing) ->
    SsopenMap (table_insert [ (existing_key, existing) ] key finalizer)
  | SsopenMap table -> SsopenMap (table_insert table key finalizer)
