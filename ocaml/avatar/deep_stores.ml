(* `raceEntrants` (`Stores.lean:1026`). *)
let race_entrants : race_name -> prog_name list = function
  | Rnempty -> []
  | RnsuccessThenSecond -> [ Pvalue (Vnat 1); Pvalue (Vnat 2) ]
  | RnfailThenSuccess -> [ PfailCause (cause_fail 1); Pvalue (Vnat 9) ]
  | RnfailThenFail -> [ PfailCause (cause_fail 1); PfailCause (cause_fail 2) ]
  (* `2f77f7d`: one entrant that parks (R2-13); a parked loser and an immediate winner (R2-12) *)
