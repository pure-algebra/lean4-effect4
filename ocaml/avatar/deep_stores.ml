(* `refStep` (`Stores.lean:457`), thirteen arms and the fall-through. `None` is a frontier: a
   key no allocation of this heap minted. Every arm is one `Effect.sync` thunk, so the read
   and the write of a read-modify-write happen with no intervening runtime step. *)
let ref_step (op : sync_op) (heap : value list) : (value * value list) option =
  let map f = Option.map f in
  match op with
  | SrefMake initial -> Some (Vhandle (List.length heap), heap @ [ initial ])
  | SrefGet cell -> map (fun a -> (a, heap)) (ref_peek heap cell)
  | SrefSet (cell, value) ->
    map (fun _ -> (Vhandle cell.index, ref_poke heap cell value)) (ref_peek heap cell)
  | SrefGetAndSet (cell, value) ->
    map (fun a -> (a, ref_poke heap cell value)) (ref_peek heap cell)
  | SrefSetAndGet (cell, value) ->
    map (fun _ -> (value, ref_poke heap cell value)) (ref_peek heap cell)
  | SrefUpdate (cell, f) ->
    map (fun a -> (Vunit, ref_poke heap cell (fn_name_total f a))) (ref_peek heap cell)
  | SrefGetAndUpdate (cell, f) ->
    map (fun a -> (a, ref_poke heap cell (fn_name_total f a))) (ref_peek heap cell)
  | SrefUpdateAndGet (cell, f) ->
    map (fun a -> (fn_name_total f a, ref_poke heap cell (fn_name_total f a)))
      (ref_peek heap cell)
  | SrefUpdateSome (cell, pf) ->
    map
      (fun a ->
        ( Vunit,
          match fn_name_partial_update pf a with
          | Some a' -> ref_poke heap cell a'
          | None -> heap ))
      (ref_peek heap cell)
  | SrefGetAndUpdateSome (cell, pf) ->
    map
      (fun a ->
        ( a,
          match fn_name_partial_update pf a with
          | Some a' -> ref_poke heap cell a'
          | None -> heap ))
      (ref_peek heap cell)
  | SrefUpdateSomeAndGet (cell, pf) ->
    Option.bind (ref_peek heap cell) (fun a ->
        match fn_name_partial_update pf a with
        | Some a' ->
          map (fun fresh -> (fresh, ref_poke heap cell a'))
            (ref_peek (ref_poke heap cell a') cell)
        | None -> Some (a, heap))
  | SrefModify (cell, f) ->
    map (fun a -> (fst (fn_name_modify f a), ref_poke heap cell (snd (fn_name_modify f a))))
      (ref_peek heap cell)
  | SrefModifySome (cell, pf) ->
    map
      (fun a ->
        ( fst (fn_name_modify_some pf a),
          ref_poke heap cell (Option.value (snd (fn_name_modify_some pf a)) ~default:a) ))
      (ref_peek heap cell)
  | _ -> None

