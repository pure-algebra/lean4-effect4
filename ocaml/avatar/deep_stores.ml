(* `ScopeStore.closeResultOf` (`Stores.lean:939`), through `Scope.closeResult`
   (`Scope.lean:796`): the three arms of rc.112 `scopeCloseUnsafe`. *)
let scope_close_result (run : fin_name -> exitv -> exitv) (self : scope) (exit_ : exitv) :
    exitv =
  if scope_is_closed self then Esuccess Vunit
  else
    match scope_close_exits run self exit_ with
    | [] -> Esuccess Vunit
    | [ only ] -> only
    | first :: second :: rest ->
      let reasons =
        List.concat_map (function Esuccess _ -> [] | Efailure c -> c.reasons)
          (first :: second :: rest)
      in
      if reasons = [] then Esuccess Vunit
      else Efailure { reasons; annotations = [] }

let scope_store_close_result_of (self : scope_store) (key : int) (exit_ : exitv) : exitv =
  match scope_store_entry_at self key with
  | None -> Esuccess Vunit
  | Some entry -> scope_close_result fin_exit entry.scope exit_

(* `voidAllOf` (`Stores.lean:948`): `exitAsVoidAll` at the value alphabet. *)
let void_all_of (reasons : reason list) : exitv =
  match reasons with
  | [] -> Esuccess Vunit
  | reason :: rest -> Efailure { reasons = reason :: rest; annotations = [] }

(* `Exit.causeReasons`. *)
let cause_reasons : exitv -> reason list = function
  | Esuccess _ -> []
  | Efailure c -> c.reasons

(* `mergeExits` (`Stores.lean:954`). *)
let merge_exits (exits : exitv list) : exitv =
  void_all_of (List.concat_map cause_reasons exits)

(* `reifyExitVal` (`Stores.lean:965`): an `Exit` as a value of the one value alphabet. The
   wire alphabet has no `exitOk`/`exitErr` pair, so this is the machine's own
   `exit_value _ MAwait` (`deep_fibers.ml:652`) and it loses the typed error -- the loss
   A0 DIVERGENCE 6 already records. *)
let reify_exit_val : exitv -> value = function
  | Esuccess value -> Vsome value
  | Efailure _ -> Vnone

(* `exitsVal` (`Stores.lean:971`): the exits a countdown collected, as one value. Lean's
   `Val.exitCons`/`exitNil` spine is the avatar's `Vlist`. Since seat F1 the machine's
   `resume_prim RexitsValue` answers the exits themselves (`Aexits`), and this is the
   projection the Lean alphabet applies (`PawaitFibers`), while the wire's `awaitAll` row
   applies its own (raw values) at `answer_countdown` -- one function, two projections at
   two sites, which closes report row W1-7. *)
let exits_val (exits : exitv list) : value = Vlist (List.map reify_exit_val exits)

(* `reasonsOfVal` (`Stores.lean:976`). Lossy at this alphabet: `reifyExitVal` mapped every
   failure to `Vnone`, so the reasons are not recoverable from the value. The Lean theorem
   `reasonsOfVal_exitsVal` (`:984`) therefore has no avatar counterpart -- a finding, not a
   defect of this function. *)
let rec reasons_of_val : value -> reason list = function
  | Vlist xs -> List.concat_map reasons_of_val xs
  | _ -> []

