(* A wire handle back to the store key it names. `handle_target` would also check the kind;
   the arms this replaces (`ref_cell`/`deferred_cell`/`scope_cell`, `deep_fibers.ml:1570-1587`
   before this port) read the owner index without checking it, and three of P5's generated
   programs pass a handle of one kind to an operation of another and rely on that. Keeping
   the laxness keeps those three running; report row W1-6 records it as a defect of the wire
   decoding, not of the store. *)
let owner_index h : int =
  match Hashtbl.find_opt handle_owner h with Some (_, id) -> id | None -> -1

let ref_key_of_handle h : ref_key = { index = owner_index h }
let deferred_key_of_handle h : deferred_key = { index = owner_index h }
let scope_key_of_handle h : int = owner_index h

let peek_exn (cell : ref_key) : value =
  match ref_peek store.refs cell with
  | Some v -> v
  | None -> failwith (Printf.sprintf "unknown ref cell %d" cell.index)

let nat_of = function Vnat n -> n | _ -> 0

(* `refStep`'s read-modify-write shape (`Stores.lean:457`) with the fixture's own closure in
   the `FnName` slot: one `Effect.sync` thunk, so the read and the write happen with no
   intervening runtime step. *)
let ref_rmw (cell : ref_key) (f : int -> int * int) : value =
  let before = nat_of (peek_exn cell) in
  let answer, after = f before in
  store.refs <- ref_poke store.refs cell (Vnat after);
  Vnat answer

let deferred_cell_exn (cell : deferred_key) : deferred_cell =
  match deferred_store_cell_at store.deferreds cell with
  | Some c -> c
  | None -> failwith (Printf.sprintf "unknown deferred cell %d" cell.index)

(* `Deferred.completeWith` at the fixture's alphabet: the first completion wins and the
   waiters it owes are queued for `dueResumes` in registration order
   (`Deferred.ts:1655-1659`, M1). *)
let arm_def_complete m f name h (exit_ : exitv) (payload : value) (ko : value kops) : unit =
  push_row (Rop (name, Vpair (Vhandle h, payload)));
  (* `done(self, exit)` = `completeWith(self, exit)` (`Deferred.ts:570-571`): the stored
     program is `Prim.ofExit exit` (`completionPrim_ofExit`) *)
  let fresh = deferred_store_complete store.deferreds (deferred_key_of_handle h)
      (prim_of_exit exit_) in
  (* Lean's `iteration` delivers the `sync`'s value into the frame and runs `Cmd.drainDue` as
     a nested command *before* the completing fiber continues, so the waiter it woke runs
     first. The service `answer` row is what the host face emits when the effect completes,
     i.e. after that nested work -- hence the drain before the row. *)
  drive m m.drive_fuel [ CdrainDue ];
  answer_row m f name (Vbool fresh) ko

(* `Deferred.await` and its flip (`Deferred.ts:173-186`): a `Prim.async` whose registration
   (`Stores.lean:1354`, `RunInterp.registerAsync`) answers at once when the cell is settled
   and otherwise adds the waiter under the token and parks; its cancel is
   `cancelName (cancelAwait cell) fiber token` (M3), the store step that splices exactly
   that waiter out (`_await`'s cleanup, `Deferred.ts:178-185`), run by the `AsyncFinalizer`
   frame's `contE` when the cause carries an interrupt (`Fibers.lean:709-712`,
   `Runtime.lean:883-888`). Seat F2: the park is `Deep_fibers.arm_async`, the PARK
   section's one `Async` primitive; the rows are the fixture's. *)
let arm_def_await m f h which (ko : value kops) : unit =
  let name = match which with `Value -> "awaitValue" | `Error -> "awaitError" in
  push_row (Rop (name, Vhandle h));
  let cell = deferred_key_of_handle h in
  (* The stored program is what the waiter continues with (Lean: `current := effect`,
     `Fibers.lean:1120-1126` for the immediate answer, `Cmd.resume` for a due one). The
     fixture projects its *exit* into the `awaitValue`/`awaitError` answer, so the program is
     run here, on the arm's stack, for that exit: exact for `Prim.ofExit` (a pure thunk), a
     refusal by name for `Completion.ofRefGet` (report row W1-2). *)
  let answer_of (p : program) : answer =
    match (which, exit_of_run p) with
    | `Value, Esuccess v -> Aval v
    | `Value, Efailure cause -> Acause cause
    | `Error, Efailure cause ->
      Aval (match cause_fail_of cause with Some e -> Vnat e | None -> Vunit)
    | `Error, Esuccess v -> Acause (cause_fail (nat_of v))
  in
  let settle (p : program) : unit =
    match answer_of p with
    | Aval v -> answer_row_now m f name v ko
    | Acause cause -> fail_op name ko cause
    | Aexits _ | Aprogram _ -> answer_row_now m f name Vunit ko
  in
  arm_async m f
    ~register:(fun token ->
      match deferred_store_register store.deferreds cell f.id token with
      | Some p -> Some (answer_of p)
      | None -> None)
    ~cancel:(Some (fun token ->
      (* M3: `SyncOp.deferredAwaitCleanup cell waiter token`, the waiter's own token *)
      ignore (sync_op_step (SdeferredAwaitCleanup (cell, f.id, token)) store)))
    ~on_answer:(fun a ->
      match a with
      (* a due resume carries the stored program, as Lean's `due` carries the effect *)
      | Aprogram p -> settle p
      | Aval _ | Aexits _ -> (
        (* a resume from outside the store (the tape's `answerAsync`): the slot is read
           back, which holds the same program the store would have carried *)
        match (deferred_cell_exn cell).completion with
        | Some p -> settle p
        | None -> answer_row_now m f name Vunit ko)
      | Acause c -> fail_op name ko c)
    ko

(* One `store_request`, one arm. The three at the head are the Lean alphabet; the rest are
   the fixture's (see the `store_request` extension above). *)
let store_arm m f (req : Deep_fibers.store_request) (ko : value kops) : unit =
  let state name request compute = arm_state m f name request compute ko in
  match req with
  (* --- the Lean alphabet ------------------------------------------------------- *)
  | Rsync op -> (
    (* `Sync[evaluate]` (`:931-935`, R2-1): the thunk, the resumes it owes (`Cmd.drainDue`
       as the nested command of `Outcome.answered`, `Fibers.lean:749-751`), then the pop
       through `deliver` (`Cmd.deliver`), whose `getCont` sees what the drain recorded. *)
    match sync_op_step op store with
    | Some v ->
      drive m m.drive_fuel [ CdrainDue ];
      deliver f ko v
    | None -> refuse "Effect4.Deep.stores.syncState (no arm)")
  | Rawait_deferred cell -> arm_def_await m f (handle_index "deferred" cell.index) `Value ko
  | Rinterrupt_deferred cell ->
    (* `Deferred.interrupt` (`Deferred.ts:1231-1232`): `withFiber` reads the id, then
       `interruptWith`, a stateful `sync` -- so the resumes it owes are drained on the spot
       (M1), before the completing fiber continues. *)
    let v =
      match sync_op_step (SdeferredInterruptWith (cell, f.id)) store with
      | Some v -> v
      | None -> Vunit
    in
    drive m m.drive_fuel [ CdrainDue ];
    deliver f ko v
  (* --- the `Refs` and `ERefs` families ------------------------------------------ *)
  | Rref_make initial ->
    push_row (Rop ("make", Vnat initial));
    let cell : ref_key = { index = List.length store.refs } in
    store.refs <- store.refs @ [ Vnat initial ];
    answer_row m f "make" (Vhandle (handle_index "ref" cell.index)) ko
  | Rref_get h -> state "get" (Vhandle h) (fun () -> peek_exn (ref_key_of_handle h))
  | Rref_set (h, v) ->
    state "set" (Vpair (Vhandle h, Vnat v)) (fun () ->
        store.refs <- ref_poke store.refs (ref_key_of_handle h) (Vnat v);
        Vunit)
  | Rref_update (h, a) ->
    state "update" (Vpair (Vhandle h, Vnat a)) (fun () ->
        ignore (ref_rmw (ref_key_of_handle h) (fun before -> (before, before + a)));
        Vunit)
  | Rref_modify (h, a) ->
    state "modify" (Vpair (Vhandle h, Vnat a)) (fun () ->
        ref_rmw (ref_key_of_handle h) (fun before -> (before, before + a)))
  | Rref_get_and_set (h, v) ->
    state "getAndSet" (Vpair (Vhandle h, Vnat v)) (fun () ->
        ref_rmw (ref_key_of_handle h) (fun before -> (before, v)))
  | Rref_try_take (h, a) ->
    state "tryTake" (Vpair (Vhandle h, Vnat a)) (fun () ->
        let cell = ref_key_of_handle h in
        let before = nat_of (peek_exn cell) in
        if before >= a then begin
          store.refs <- ref_poke store.refs cell (Vnat (before - a));
          Vpair (Vbool true, Vnat (before - a))
        end
        else Vpair (Vbool false, Vstring "underflow"))
  (* --- the `Deferreds` family ---------------------------------------------------- *)
  | Rdef_make ->
    push_row (Rop ("make", Vunit));
    let cell = deferred_store_make store.deferreds in
    answer_row m f "make" (Vhandle (handle_index "deferred" cell.index)) ko
  | Rdef_succeed (h, v) -> arm_def_complete m f "succeed" h (Esuccess (Vnat v)) (Vnat v) ko
  | Rdef_fail (h, e) -> arm_def_complete m f "fail" h (Efailure (cause_fail e)) (Vnat e) ko
  | Rdef_is_done h ->
    state "isDone" (Vhandle h) (fun () ->
        Vbool
          (match deferred_store_is_done store.deferreds (deferred_key_of_handle h) with
           | Some b -> b
           | None -> false))
  | Rdef_poll h ->
    (* The fixture's `poll` answers the completion's *exit*; `SyncOp.deferredPoll`
       (`Stores.lean:234`, `:1215-1216`) answers `Val.bool slot.isSome`, because Lean's slot
       holds a `Program` it must not run. The avatar's slot holds that program; the fixture
       runs it here for its exit, which is exact for `Prim.ofExit` (every program the
       fixture stores) and refuses by name for `Completion.ofRefGet`. Report row W1-4. *)
    state "poll" (Vhandle h) (fun () ->
        match (deferred_cell_exn (deferred_key_of_handle h)).completion with
        | None -> Vnone
        | Some p -> (
          match exit_of_run p with
          | Esuccess v -> Vsome (Vpair (Vbool true, v))
          | Efailure c ->
            Vsome
              (Vpair (Vbool false, match cause_fail_of c with Some e -> Vnat e | None -> Vunit))))
  | Rdef_await_value h -> arm_def_await m f h `Value ko
  | Rdef_await_error h -> arm_def_await m f h `Error ko
  (* --- the `Scopes` family -------------------------------------------------------- *)
  | Rscope_make ->
    push_row (Rop ("make", Vunit));
    let key = store.next_name in
    scope_store_make store.scopes key Fssequential;
    store.next_name <- key + 1;
    answer_row m f "make" (Vhandle (handle_index "scope" key)) ko
  | Rscope_add (h, key) ->
    state "addFinalizer" (Vpair (Vhandle h, Vnat key)) (fun () ->
        let scope = scope_key_of_handle h in
        let was_open =
          match scope_store_status store.scopes scope with Some None -> true | _ -> false
        in
        ignore (scope_store_add_finalizer store.scopes scope key (Finrelease (key, false)));
        Vbool was_open)
  | Rscope_remove (h, key) ->
    state "remove" (Vpair (Vhandle h, Vnat key)) (fun () ->
        scope_store_remove_finalizer store.scopes (scope_key_of_handle h) key;
        Vunit)
  | Rscope_close h ->
    state "close" (Vhandle h) (fun () ->
        let scope = scope_key_of_handle h in
        (* `storesCloseScope` (`Stores.lean:1143`): the close order is read before
           `closeState` writes, and a closed scope's order is empty. *)
        let order = scope_store_close_order_of store.scopes scope in
        scope_store_close_state store.scopes scope (Esuccess Vunit);
        Vlist
          (List.map
             (function Finrelease (label, _) -> Vnat label | _ -> Vunit)
             order))
  | _ -> refuse "Effect4.Deep.stores (unknown store_request)"

(* `stores : RunInterp Name Thunk Val Err Defect FiberId Ann Ctx Stores`
   (`Stores.lean:1293`), the slots the machine calls. Field for field with the Lean record,
   minus the ones the substitution makes unreachable (`contA`, `contE`, `withFiberOf`,
   `parkOf`, `finalizerProgram`, `restoreName`, `mergeName`, `cancelName`, `abortName`,
   `reifyExit`, `exitValue`, `fiberValue`, `fibersValue`, `exitsValue`, `voidValue`,
   `encodeFiber`, `iterNext`/`loop*`, `suspendBody`, `finalizerExit`, `notImplemented`,
   `cancelThenFail`, `syncValue`, `emptyContext`, `contextValue`, `ambientScope`,
   `budgetOf`, `stackAnnotations`, `asyncFiberError`) -- those are the avatar's own control
   or the fixture's, and the report lists every one. *)
let stores : run_interp =
  { store_arm;
    (* `RunInterp.dueResumes` (`Fibers.lean:414`) = `Stores.lean:1362`. *)
    due_resumes = (fun () -> deferred_store_drain_due store.deferreds);
    (* `RunInterp.scopeStatus` (`:427`) = `Stores.lean:1370`. *)
    scope_status = (fun scope -> scope_store_status store.scopes scope);
    (* `RunInterp.scopeLinkFiber` (`:431`) = `Stores.lean:1371`. `forkIn` registers the
       self-guarded finalizer (`:5370`), `fiberRunIn` the unguarded one (`:5458`) -- M4.
       `Supervision.ScopeMode` is an int in the substitution: 0 is `forkIn`. *)
    scope_link_fiber =
      (fun mode scope key fiber ->
        match scope_store_entry_at store.scopes scope with
        | None -> false
        | Some _ ->
          let skip_self = mode = 0 in
          ignore
            (scope_store_add_finalizer store.scopes scope key
               (FininterruptFiber (fiber, skip_self)));
          true);
    (* `RunInterp.dropFinalizer` (`:434`) = `Stores.lean:1382`. *)
    drop_finalizer =
      (fun scope key ->
        match scope_store_entry_at store.scopes scope with
        | None -> false
        | Some _ ->
          scope_store_remove_finalizer store.scopes scope key;
          true);
    (* `RunInterp.closeScope` (`:440`) = `Stores.lean:1386`. *)
    close_scope =
      (fun scope exit_ closer_interruptible _closer ->
        stores_close_scope scope exit_ closer_interruptible store);
    (* `RunInterp.stackAnnotations` (`:457`) = `Stores.lean:1283`. *)
    stack_annotations = stack_annotations_of }

