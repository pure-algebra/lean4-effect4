(* `ScopeStore.closeState` (`Stores.lean:931`): state first. *)
let scope_store_close_state (self : scope_store) (key : int) (exit_ : exitv) : unit =
  match scope_store_entry_at self key with
  | None -> ()
  | Some entry ->
    scope_close_state entry.scope exit_;
    scope_store_set_entry self entry

