(* `DeferredStore.register` (`Stores.lean:719-728`), the store half of `registerAsync`:
   resume at once with the stored effect when done, otherwise append this waiter in
   registration order and park. *)
let deferred_store_register (self : deferred_store) (cell : deferred_key) (waiter : int)
    (token : int) : program option =
  match deferred_store_cell_at self cell with
  | None -> None
  | Some c -> (
    match c.completion with
    | Some effect -> Some effect
    | None ->
      c.waiters <- c.waiters @ [ (waiter, token) ];
      deferred_store_set_cell self cell c;
      None)

(* `DeferredStore.cancel` (`Stores.lean:705`): splice this waiter out, order-preserving; a
   no-op once completion has cleared the array. *)
let deferred_store_cancel (self : deferred_store) (cell : deferred_key) (waiter : int)
    (token : int) : unit =
  match deferred_store_cell_at self cell with
  | None -> ()
  | Some c ->
    c.waiters <- List.filter (fun (w, t) -> not (w = waiter && t = token)) c.waiters;
    deferred_store_set_cell self cell c

(* `DeferredStore.complete` (`Stores.lean:739-751`): a completion attempt answers `false` and
   changes nothing when an effect is already stored; otherwise the effect is stored, the
   waiter list is *cleared*, and every waiter is owed a resume with that effect in
   registration order. The `answer` a due resume carries (`due_pair`'s third component, the
   avatar's `Prim`, DIVERGENCE 1) is `Aprogram effect`, the stored program itself, as Lean's
   `(w.1, w.2, effect)` (`:751`). *)
let deferred_store_complete (self : deferred_store) (cell : deferred_key)
    (effect : program) : bool =
  match deferred_store_cell_at self cell with
  | None -> false
  | Some c -> (
    match c.completion with
    | Some _ -> false
    | None ->
      let waiters = c.waiters in
      c.completion <- Some effect;
      c.waiters <- [];
      deferred_store_set_cell self cell c;
      self.due <- self.due @ List.map (fun (w, t) -> (w, t, Aprogram effect)) waiters;
      true)

(* `DeferredStore.drainDue` (`Stores.lean:727`): the resumes the store owes now, in
   registration order. *)
let deferred_store_drain_due (self : deferred_store) : due_pair list =
  let due = self.due in
  self.due <- [];
  due

