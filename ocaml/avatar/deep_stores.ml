  match scope_store_entry_at self key with
  | None -> ()
  | Some entry ->
    scope_remove_unsafe entry.scope finalizer_key;
    scope_store_set_entry self entry

(* `ScopeStore.forkChild` (`Stores.lean:905`). *)
let scope_store_fork_child (self : scope_store) (parent_key : int) (child_key : int)
    (shared_key : int) (strategy : finalizer_strategy) : unit =
  match scope_store_entry_at self parent_key with
  | None -> ()
  | Some parent ->
    let child_scope =
      scope_fork parent.scope strategy shared_key
        (FincloseChildScope child_key)
        (FindetachFromParent (parent_key, shared_key))
    in
    scope_store_set_entry self parent;
    self.entries <- self.entries @ [ { key = child_key; scope = child_scope } ]

(* `ScopeStore.status` (`Stores.lean:919`): `None` unknown, `Some None` open,
   `Some (Some exit)` closed. *)
