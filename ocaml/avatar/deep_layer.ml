let sync_op (op : sync_op) : program = fun () -> Effect.perform (Op_store (Rlayer_sync op))

(* `progOf` (`Layer.lean:931`), `contAOf` (`:1087`), `contEOf` (`:1184`), `actionOf` (`:1197`),
   `raceSettleProgram`, `cancelProgram` (`:1191`) and `interp` (`:1216`): every arm that reads
   or sets the fiber's context refuses by name -- `χ` is `unit` here (A0 §18). The arms that
   need no context are ported. *)
let rec prog_of (table : layer_desc list) (p : prog_name) : program =
  match p with
  | Lpvalue v -> fun () -> v
  | LpfailCause cause -> fun () -> raise (Einterrupt_exn cause)
  | Lpseq (first, second) ->
    fun () ->
      ignore (prog_of table first ());
      prog_of table second ()
  | Lpnever -> fun () -> Effect.perform (Op_never ())
  | LpcloseScope (scope, exit_) ->
    fun () ->
      ignore (Effect.perform (Op_close_scope (scope, exit_)));
      take_current_program () ()
  | LpfinalizerOf (fin, exit_) -> fin_program table fin exit_
  | LpreleaseOf _label -> fun () -> Vunit
  | LpmemoReleaseOf (layer, memo_map, exit_) ->
    (* the entry finalizer's `suspend` body (`Layer.ts:402-408`): `memoRelease`, then
       `closeIfLast` -- close the layer scope only when the count hit zero *)
    fun () -> (
      match Effect.perform (Op_store (Rlayer_sync (LsmemoRelease (layer, memo_map)))) with
      | Vhandle h -> (
        match Hashtbl.find_opt handle_owner h with
        | Some ("layerScope", scope) ->
          ignore (Effect.perform (Op_close_scope (scope, exit_)));
          take_current_program () ()
        | _ -> Vunit)
      | _ -> Vunit)
  | LpgetContext -> refuse "Effect4.Deep.Layers.progOf (ProgName.getContext)"
  | Lpservice _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.service)"
  | LpsetContextTo _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.setContextTo)"
  | LpprovideContext _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.provideContext)"
  | LpprovideService _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.provideService)"
  | Lpscoped _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.scoped)"
  | LpacquireRelease _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.acquireRelease)"
  | LpacquireMasked _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.acquireMasked)"
  | LpaddFinalizer _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.addFinalizer)"
  | Lpbuild _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.build)"
  | LpbuildWithScope _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.buildWithScope)"
  | LpbuildWithMemoMap _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.buildWithMemoMap)"
  | LplayerBuild _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.layerBuild)"
  | LpbuildAdding _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.buildAdding)"
  | LpbuildThenNever _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.buildThenNever)"
  | Lplaunch _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.launch)"
  | LpprovideLayer _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.provideLayer)"
  | LpscopedWithAlloc _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.scopedWithAlloc)"
  | LpmemoLookup _ -> refuse "Effect4.Deep.Layers.progOf (ProgName.memoLookup)"

(* `finProgram` (`Layer.lean:874`): the program a scope finalizer name runs. *)
and fin_program (table : layer_desc list) (fin : fin_name) (exit_ : exitv) : program =
  match fin with
  | LfincloseChildScope scope ->
    fun () ->
      ignore (Effect.perform (Op_close_scope (scope, exit_)));
      take_current_program () ()
  | LfindetachFromParent (parent, key) -> sync_op (LsscopeRemove (parent, key))
  | LfincloseChildOnFailure scope -> (
    match exit_ with
    | Efailure _ ->
      fun () ->
        ignore (Effect.perform (Op_close_scope (scope, exit_)));
        take_current_program () ()
    | Esuccess _ -> fun () -> Vunit)
  | LfinmemoEntry (layer, memo_map) -> prog_of table (LpmemoReleaseOf (layer, memo_map, exit_))
  | LfinmemoDone (layer, memo_map) -> sync_op (LsmemoComplete (layer, memo_map, exit_))
  | Lfinrelease (label, fails) -> fun () -> if fails then raise (Efail_exn label) else Vunit
  | LfininterruptFiber (fiber, true) -> fun () -> Effect.perform (Op_interrupt_scoped fiber)
  | LfininterruptFiber (fiber, false) -> fun () -> Effect.perform (Op_interrupt_fiber fiber)
  | LfinrestoreContext _ -> refuse "Effect4.Deep.Layers.finProgram (FinName.restoreContext)"
  | LfinscopedExit _ -> refuse "Effect4.Deep.Layers.finProgram (FinName.scopedExit)"
  | LfincloseScopeWith _ -> refuse "Effect4.Deep.Layers.finProgram (FinName.closeScopeWith)"
  | LfinreleaseWith _ -> refuse "Effect4.Deep.Layers.finProgram (FinName.releaseWith)"

