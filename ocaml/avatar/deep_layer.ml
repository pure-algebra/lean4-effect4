(* `Val.scopeHandle`/`Val.memoMap`/`Val.promise` at the wire (W1-1). *)
let scope_handle (scope : int) : value = Vhandle (handle_index "layerScope" scope)
let memo_map_handle (id : int) : value = Vhandle (handle_index "memoMap" id)
let promise_handle (cell : int) : value = Vhandle (handle_index "deferred" cell)

(* `syncStep` (`Layer.lean:698-763`), arm for arm; `None` is a frontier (M7). The store is
   written in place, so the Lean pair `(St × Val)` is the `Val` alone. *)
let sync_step (op : sync_op) (st : st) : value option =
  match op with
  | LsscopeMake strategy ->                                             (* :699-701 *)
    let key = st.next_name in
    scope_store_make st.scopes key strategy;
    st.next_name <- key + 1;
    Some (scope_handle key)
  | LsscopeFork (parent, strategy) -> (                                (* :702-709 *)
    match scope_store_entry_at st.scopes parent with
    | None -> None
    | Some _ ->
      let child = st.next_name in
      scope_store_fork_child st.scopes parent child (child + 1) strategy;
      st.next_name <- child + 2;
      Some (scope_handle child))
  | LsscopeAdd (scope, fin) -> (                                        (* :710-720 *)
    match scope_store_entry_at st.scopes scope with
    | None -> None
    | Some entry -> (
      match scope_closing_exit entry.scope with
      | Some exit_ -> Some (reify_exit_val exit_)                       (* :3852-3853 *)
      | None ->
        scope_add_unsafe entry.scope st.next_name fin;
        st.next_name <- st.next_name + 1;
        Some Vunit))                                                    (* :3855-3856 *)
  | LsscopeRemove (scope, key) ->                                       (* :721-722 *)
    scope_store_remove_finalizer st.scopes scope key;
    Some Vunit
  | LsmemoFork parent ->                                                (* :723-725 *)
    let id = st.next_name in
    st.memo <- st.memo @ [ { id = { index = id }; parent; entries = [] } ];
    st.next_name <- id + 1;
    Some (memo_map_handle id)
  | LsmemoGet (layer, memo_map) -> (                                    (* :726-731 *)
    match memo_world_get st.memo layer memo_map with
    | None -> Some Vunit
    | Some (owner, entry) ->
      memo_world_update_entry st.memo owner layer (fun e -> e.observers <- e.observers + 1);
      Some (Vpair (promise_handle entry.deferred.index, memo_map_handle owner.index)))
  | LsmemoBuild (layer, memo_map) ->                                    (* :732-744 *)
    let layer_scope = st.next_name in
    let deferred = deferred_store_make st.deferreds in
    let entry : memo_entry =
      { observers = 1;
        (* `Prim.async (registerAwait deferred) true (some (cancelAwait deferred))`: the
           await of the cell, as a thunk (DIVERGENCE 1) *)
        effect = (fun () -> Effect.perform (Op_store (Deep_stores.Rawait_deferred deferred)));
        layer_scope; deferred; finalizer = LfinmemoEntry (layer, memo_map) }
    in
    scope_store_make st.scopes layer_scope Deep_stores.Fssequential;
    memo_world_insert_entry st.memo memo_map layer entry;
    st.next_name <- layer_scope + 1;
    Some (scope_handle layer_scope)
  | LsmemoComplete (layer, memo_map, exit_) -> (                        (* :745-753 *)
    match memo_world_entry_at st.memo memo_map layer with
    | None -> Some Vunit
    | Some entry ->
      (* `done(deferred, exit)` = `completeWith (Prim.ofExit exit)`: the stored program *)
      ignore (deferred_store_complete st.deferreds entry.deferred (Deep_stores.prim_of_exit exit_));
      memo_world_update_entry st.memo memo_map layer (fun e ->
          e.effect <- (fun () -> match exit_ with Esuccess v -> v | Efailure c -> raise (Einterrupt_exn c)));
      Some Vunit)
  | LsmemoRelease (layer, memo_map) -> (                                (* :754-761 *)
    match memo_world_entry_at st.memo memo_map layer with
    | None -> Some Vunit
    | Some entry ->
      if entry.observers <= 1 then begin
        memo_world_delete_entry st.memo memo_map layer;
        Some (scope_handle entry.layer_scope)
      end
      else begin
        memo_world_update_entry st.memo memo_map layer (fun e -> e.observers <- e.observers - 1);
        Some Vunit
      end)
  | LsdeferredAwaitCleanup (cell, waiter, token) ->                     (* :762-763 *)
    deferred_store_cancel st.deferreds cell waiter token;
    Some Vunit

