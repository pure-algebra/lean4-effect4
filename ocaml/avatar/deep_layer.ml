let add_state (state : scope_state) (key : int) (finalizer : fin_name) : scope_state =
  match state with
  | Lssempty | LssopenEmpty -> LssopenInline (key, finalizer)
  | LssopenInline (existing_key, existing) ->
    LssopenMap (table_insert [ (existing_key, existing) ] key finalizer)
  | LssopenMap table -> LssopenMap (table_insert table key finalizer)
  | Lssclosed exit_ -> Lssclosed exit_

