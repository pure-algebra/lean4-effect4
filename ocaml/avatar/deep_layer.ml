(* `Scope.fork` (`Scope.lean:1036`): one shared key links a parent finalizer closing the
   child to a child finalizer removing itself from the parent; a closed parent's child is
   born closed (`scopeFork_links`, `Layer.lean:1333`). *)
let scope_fork (parent : scope) (strategy : Deep_stores.finalizer_strategy) (key : int)
    (close_child : fin_name) (detach_from_parent : fin_name) : scope =
  match scope_closing_exit parent with
  | Some exit_ -> { strategy; state = Lssclosed exit_ }
  | None ->
    scope_add_unsafe parent key close_child;
    let child = scope_make strategy in
    scope_add_unsafe child key detach_from_parent;
    child

