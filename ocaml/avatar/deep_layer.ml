(* `ctxOfList` (`:682`): a context from a service list, by `addV` in order -- the later
   binding of a key wins (`Context.add`, `Context.lean:376`). *)
let ctx_add (ctx : service_pair list) (key : Deep_context.service_key) (v : value) : service_pair list =
  if List.exists (fun (k, _) -> k = key) ctx then
    List.map (fun (k, x) -> if k = key then (k, v) else (k, x)) ctx
  else ctx @ [ (key, v) ]

let rec ctx_of_list : service_pair list -> service_pair list = function
  | [] -> []
  | (key, v) :: rest -> ctx_add (ctx_of_list rest) key v

