(* JavaScript `Map.prototype.set` (`Scope.lean:326`): overwrite in place, else append. *)
let table_insert (table : scope_entry_pair list) (key : int) (finalizer : fin_name) :
    scope_entry_pair list =
  if List.exists (fun (k, _) -> k = key) table then
    List.map (fun (k, f) -> if k = key then (key, finalizer) else (k, f)) table
  else table @ [ (key, finalizer) ]

(* JavaScript `Map.prototype.delete` (`Scope.lean:334`). *)
let table_remove (table : scope_entry_pair list) (key : int) : scope_entry_pair list =
  List.filter (fun (k, _) -> k <> key) table

