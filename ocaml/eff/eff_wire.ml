let rec decode_eff_ty (s : string) (pos : int) (limit : int) : (eff_ty * int) option =
  match Eff_frame.read_ctor s pos limit with
  | None -> None
  | Some (i, p, e, next) ->
    (match i with
    | 0 ->
      (match decode_ty s p e with
       | None -> None
       | Some (a0, p) ->
        (match decode_ty s p e with
         | None -> None
         | Some (a1, p) ->
          (match (Eff_frame.decode_list decode_service_key) s p e with
           | None -> None
           | Some (a2, p) ->
            if p = e then Some ({ eff_ty_answer = a0; eff_ty_error = a1; eff_ty_requires = a2 }, next) else None)))
    | _ -> None)

let decode_eff_ty_exact (s : string) : eff_ty option = Eff_frame.exact decode_eff_ty s

(* The top level: a program is an Eff over the native alphabet. *)
let encode_program : eff -> string = encode_eff
let decode_program : string -> (eff * int) option = fun s -> decode_eff s 0 (String.length s)
let decode_program_exact : string -> eff option = decode_eff_exact
