    | None -> None
    | Some (i, p, e, next) -> (match i with
        | 0 -> (match decode_term s p e with
            | None -> None
            | Some (a0, p) -> if p = e then Some (Eff_succeed a0, next) else None)
        | 1 -> (match decode_term s p e with
            | None -> None
            | Some (a0, p) -> if p = e then Some (Eff_fail a0, next) else None)
