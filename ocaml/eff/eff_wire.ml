    | ActionTerm_context a0 -> Eff_frame.emit_ctor b 18 (fun b -> if not (Eff_frame.strictly_ascending keyBefore a0) then invalid_arg "noncanonical requirements"; Eff_frame.emit_list b emit_service_key a0)

