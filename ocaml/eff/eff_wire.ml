    | Eff_service a0 -> Eff_frame.emit_ctor b 24 (fun b -> emit_service_key b a0)
    | Eff_provideService (a0, a1, a2) -> Eff_frame.emit_ctor b 25 (fun b -> emit_service_key b a0; emit_term b a1; emit_eff b a2)
