(* The `Fibers` family's fixture, transcribed from `harness/trace/fiber-fixture.ts` (which is
   itself generated by `harness/trace/Generate.lean` from the Lean family). The nine bodies
   are the nine goldens under `generated/traces/fiber/`.

   A fork names a declared root, never a closure (`fork-lowering.md` §(b)): the root table is
   `body`, keyed by the numeric code the golden's `op fork <code>` row carries. *)

open Deep_fibers

let state : st = { started = []; cleanups = [] }

(* The child body table, the same numeric table the Lean face and `fiber-tail.ts` carry:
   0 succeeds with 11, 1 with 22, 2 fails with 1, 3 fails with 2, anything else is
   `Effect.never`. Every body appends its code to `started` when it is given the processor
   and to `cleanups` when its `onExit` runs. *)
let body (code : int) : unit -> value =
 fun () ->
  Fun.protect
    ~finally:(fun () -> state.cleanups <- state.cleanups @ [ code ])
    (fun () ->
      state.started <- state.started @ [ code ];
      match code with
      | 0 -> Vnat 11
      | 1 -> Vnat 22
      | 2 -> raise (Efail_exn 1)
      | 3 -> raise (Efail_exn 2)
      | _ -> Effect.perform (Op_never ()))

let () = body_of_code := body

(* The service surface, one function per `FibersRows` row. *)
let handle = function Vhandle h -> h | _ -> failwith "not a handle"
let fork code = Effect.perform (Op_fork (code, false))
let fork_detach code = Effect.perform (Op_fork (code, true))
let join f = Effect.perform (Op_join (handle f))
let await_value f = Effect.perform (Op_await_value (handle f))
let await_error f = Effect.perform (Op_await_error (handle f))
let interrupt f = ignore (Effect.perform (Op_interrupt (handle f)))
let started () = Effect.perform (Op_started ())
let cleanups () = Effect.perform (Op_cleanups ())

(* ------------------------------------------------------------------ the nine programs *)

let fiber_race_immediate_success_stops_launch () =
  let _a = fork 0 in
  let b = fork 1 in
  let s = started () in
  interrupt b;
  s

let fiber_race_failure_allows_next_launch () =
  let a = fork 2 in
  let _e = await_error a in
  let _b = fork 1 in
  let s = started () in
  s

let fiber_race_all_failures_retain_order () =
  let a = fork 2 in
  let b = fork 3 in
  let c = fork 2 in
  ignore (await_error a);
  ignore (await_error b);
  ignore (await_error c);
  let s = cleanups () in
  s

let fiber_empty_race_pending_until_interrupted () =
  let a = fork 4 in
  let _s = started () in
  interrupt a;
  let _v = await_value a in
  let _e = await_error a in
  let c = cleanups () in
  c

let fiber_parent_publishes_after_child_cleanup () =
  let a = fork 4 in
  let _b = cleanups () in
  interrupt a;
  let _v = await_value a in
  let c = cleanups () in
  c

let fiber_daemon_survives_parent_exit () =
  let _d = fork_detach 4 in
  let _s = started () in
  let c = cleanups () in
  c

let fiber_await_value_distinct_from_join_effect () =
  let a = fork 2 in
  let _v = await_value a in
  let _e = await_error a in
  let y = join a in
  y

let fiber_race_reentrant_empty_set_bypasses () =
  let w = fork 0 in
  let l = fork 4 in
  let _x = await_value w in
  let s = started () in
  interrupt l;
  let _y = await_value l in
  s

let fiber_parent_interrupt_during_child_wait () =
  let a = fork 0 in
  interrupt a;
  let _x = await_value a in
  let b = fork 4 in
  interrupt b;
  let y = await_value b in
  y

let programs : (string * (unit -> value)) list =
  [ ("raceImmediateSuccessStopsLaunch", fiber_race_immediate_success_stops_launch);
    ("raceFailureAllowsNextLaunch", fiber_race_failure_allows_next_launch);
    ("raceAllFailuresRetainOrder", fiber_race_all_failures_retain_order);
    ("emptyRacePendingUntilInterrupted", fiber_empty_race_pending_until_interrupted);
    ("parentPublishesAfterChildCleanup", fiber_parent_publishes_after_child_cleanup);
    ("daemonSurvivesParentExit", fiber_daemon_survives_parent_exit);
    ("awaitValueDistinctFromJoinEffect", fiber_await_value_distinct_from_join_effect);
    ("raceReentrantEmptySetBypasses", fiber_race_reentrant_empty_set_bypasses);
    ("parentInterruptDuringChildWait", fiber_parent_interrupt_during_child_wait) ]
