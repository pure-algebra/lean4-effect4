#!/usr/bin/env python3
"""Generate the engine program mirror from selected source data and actual engine declarations.

Properties: no independent family or ordinal list; exact named payload checks. A family the
engine declares at fewer members than the source REFUSES unless the allowance file names it
(--allowance, `ocaml/engine/layout-allowance.json`, empty today); a family the engine does not
declare at all is reported as an absent boundary, because the mirror is the intersection. This
does not regenerate or certify the engine. Products are written only after validation.
"""
import argparse
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent/'lib'))
from program_structure import selected_view

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'scripts/generate-engine-structure.py'

def allowance_families(text):
    data = json.loads(text)
    if data.get('format') != 'effect4-engine-layout-allowance-v1':
        raise ValueError('unsupported layout allowance format')
    families = data['allowed']
    if not isinstance(families, list) or not all(isinstance(f, str) for f in families):
        raise ValueError('layout allowance: `allowed` is a list of family names')
    return families

def emit(descriptor, engine, allowance=()):
    common, boundaries = selected_view(descriptor, engine, allowance)
    # Retain the source's mutual groups. One giant recursive group merges independent
    # record-label scopes (e.g. ServiceKey.name and Row.name) and fails OCaml warning 30.
    groups = {family['name']: index for index, block in enumerate(descriptor['blocks'])
              for family in block}
    definitions = []
    previous = None
    for family, declaration, _ in common:
        group = groups[family['name']]
        definitions.append(('  and ' if group == previous else '  type ') +
                           declaration.head + ' = ' + declaration.body)
        previous = group
    signature = 'module type PROGRAM_TYPES = sig\n' + '\n'.join(definitions) + '\nend\n'
    source_rows = []
    engine_rows = []
    for family, _, names in common:
        if family['structure']: continue
        label = family['label']
        source_rows.append(f'  ({json.dumps(label)}, Eff_types.ctor_names_{label})')
        engine_rows.append(f'  ({json.dumps(label)}, [' + '; '.join(map(json.dumps, names)) + '])')
    text = signature + '\nlet source_ctor_names = [\n' + ';\n'.join(source_rows) + '\n]\n'
    text += '\nlet engine_ctor_names = [\n' + ';\n'.join(engine_rows) + '\n]\n'
    report = {'format':'effect4-engine-structure-v1',
              'claim':'selected source shape checked against the engine declarations; a family declared at fewer members than the source refuses unless ocaml/engine/layout-allowance.json names it; `unavailable` lists the families the engine does not declare at all, plus any allowed lag',
              'families':[family['name'] for family,_,_ in common], 'unavailable':boundaries}
    return text, json.dumps(report, indent=2) + '\n'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--descriptor', type=Path, default=ROOT/'ocaml/eff/program-structure.json')
    parser.add_argument('--engine', type=Path, default=ROOT/'ocaml/engine/api_engine.ml')
    parser.add_argument('--allowance', type=Path, default=ROOT/'ocaml/engine/layout-allowance.json')
    parser.add_argument('--out', type=Path, default=ROOT/'ocaml/engine')
    args = parser.parse_args()
    code, report = emit(json.loads(args.descriptor.read_text()), args.engine.read_text(),
                        allowance_families(args.allowance.read_text()))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out/'e4_program_layout.ml').write_text(
        f'(* GENERATED by {SOURCE}; do not edit *)\n' + code)
    (args.out/'e4_program_layout.json').write_text(report)
    print('engine structure: generated selected mirror and explicit historical boundaries')

if __name__ == '__main__':
    try: main()
    except (ValueError, KeyError, OSError) as error:
        raise SystemExit('FAIL engine structure: ' + str(error))
