"""vessel_to_ml.py -- the vessel's saved native runs as an OCaml module of values.

What it is: each replay.json that apps/vessel/check_replay.lean checked (branch
codex/vessel-dogfood; the six files apps/vessel/evidence/replay-check.log lists by SHA-256) holds
the closed program's bytes, each host reply with its request, and the root's exit. This writes,
for run i: `program_i` (decoded from programHex by Eff_wire and printed by the OCaml toplevel),
`requests_i` (each call's request), `replies_i` (each reply, success or a tagged failure) and
`exit_i`. A value's tagged JSON (["nat","2000"], ["str",s], ["ctor",i,[...]], ...) is printed as
the OCaml constructor it names; check_vessel.ml reads the module back and compares every value
with the JSON, and every program with its bytes.

Run from the repository root:
    python3 docs/research/2026-10-16-itrees/gen/vessel_to_ml.py OUT.ml REPLAY.json...
"""
import json, os, re, subprocess, sys

ROOT = os.getcwd()
BUILD = os.path.join(ROOT, "ocaml/_build/default/eff")

def val(v):
    tag = v[0]
    if tag == "nat": return "(Eff_types.Val_nat %d)" % int(v[1])
    if tag == "str": return "(Eff_types.Val_str %s)" % ocaml_string(v[1])
    if tag == "bool": return "(Eff_types.Val_bool %s)" % ("true" if v[1] else "false")
    if tag == "unit": return "Eff_types.Val_unit"
    if tag == "list": return "(Eff_types.Val_list [%s])" % "; ".join(val(x) for x in v[1])
    if tag == "ctor": return "(Eff_types.Val_ctor (%d, [%s]))" % (v[1], "; ".join(val(x) for x in v[2]))
    sys.exit("vessel_to_ml: no constructor for %r" % (tag,))

def reply(r):
    if "success" in r: return "(Succeeded %s)" % val(r["success"])
    t, m = r["failure"]
    return "(Failed (%s, %s))" % (ocaml_string(t), ocaml_string(m))

def ocaml_string(s):
    # OCaml string literal: escape backslash, quote and every byte outside printable ASCII
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == "\\": out.append("\\\\")
        elif c == '"': out.append('\\"')
        elif 32 <= b < 127: out.append(c)
        else: out.append("\\%03d" % b)
    return '"%s"' % "".join(out)

def main(out, paths):
    runs = [json.load(open(p)) for p in paths]
    script = ["#print_depth 100000000;;", "#print_length 100000000;;",
              "let dec h = match Eff_wire.decode_program_exact (String.init (String.length h / 2) "
              "(fun i -> Char.chr (int_of_string (\"0x\" ^ String.sub h (2 * i) 2)))) with "
              "Some p -> p | None -> failwith \"program\";;"]
    for i, r in enumerate(runs):
        script.append('print_endline "@@program_%d";;' % i)
        script.append('dec "%s";;' % r["programHex"])
    proc = subprocess.run(
        ["opam", "exec", "--switch=effect4", "--", "ocaml", "-noprompt", "-I",
         os.path.join(BUILD, ".effect4_eff.objs/byte"), os.path.join(BUILD, "effect4_eff.cma")],
        input="\n".join(script) + "\n", capture_output=True, text=True, check=True)
    text = re.sub(r"^- : unit = \(\)\n", "", proc.stdout, flags=re.M)
    parts = re.split(r"^@@(\w+)\n", text, flags=re.M)
    programs = {}
    for k in range(1, len(parts), 2):
        m = re.match(r"- : (.*?) =\s(.*)", parts[k + 1], flags=re.S)
        if not m: sys.exit("vessel_to_ml: no program printed for %s" % parts[k])
        programs[parts[k]] = m.group(2).strip()
    with open(out, "w") as f:
        f.write("(* GENERATED by docs/research/2026-10-16-itrees/gen/vessel_to_ml.py from the vessel's\n"
                "   saved native runs (apps/vessel/artifacts/*/replay.json, checked by Lean). Do not edit. *)\n\n")
        f.write("(* A reply or an exit: a success, or a tagged failure; not named Success or Failure, which\n   rocq-of-ocaml reads as OCaml's exception Failure (Cause.fail (.tagged tag message)). *)\n"
                "type outcome = Succeeded of Eff_types.val_ | Failed of string * string\n\n")
        f.write("let count = %d\n\n" % len(runs))
        for i, r in enumerate(runs):
            f.write("let source_%d : string = %s\n\n" % (i, ocaml_string(os.path.basename(os.path.dirname(paths[i])))))
            f.write("let program_%d : Eff_types.native_op Eff_types.eff =\n  %s\n\n" % (i, programs["program_%d" % i]))
            f.write("let requests_%d : Eff_types.val_ list = [%s]\n\n" % (i, "; ".join(val(x["request"]) for x in r["replies"])))
            f.write("let replies_%d : outcome list = [%s]\n\n"
                    % (i, "; ".join(reply(x["reply"]) for x in r["replies"])))
            f.write("let exit_%d : outcome = %s\n\n" % (i, reply(r["exit"])))
    print("wrote %s: %d runs" % (out, len(runs)))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2:])
