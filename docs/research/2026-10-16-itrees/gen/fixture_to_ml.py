"""fixture_to_ml.py -- the to-do fixture as an OCaml module of values, printed by the toplevel.

What it is: runs the OCaml toplevel (effect4 switch) on fixture_values.ml, asks it to print each
request's program, calls and exit, and writes each printed value as one `let` of a module. The
toplevel is the printer: it prints any value of a known type as OCaml source, so no printer is
written by hand. check_fixture.ml re-encodes the module's values and compares Lean's bytes.

Run from the repository root:
    python3 docs/research/2026-10-16-itrees/gen/fixture_to_ml.py OUT.ml
It reads ocaml/engine/test/todo/todo-host.txt and the bytecode library ocaml/_build/default/eff
(build it first: cd ocaml && opam exec --switch=effect4 -- dune build eff).
"""
import os, re, subprocess, sys

ROOT = os.getcwd()
HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(ROOT, "ocaml/_build/default/eff")
FIXTURE = os.path.join(ROOT, "ocaml/engine/test/todo/todo-host.txt")

def main(out):
    count = sum(1 for l in open(FIXTURE) if l.startswith("request "))
    script = ['#use "%s";;' % os.path.join(HERE, "fixture_values.ml")]
    names = []
    for i in range(count):
        for name, expr in [("program", "List.nth programs %d" % i),
                           ("calls", "fst (List.nth results %d)" % i),
                           ("exit", "snd (List.nth results %d)" % i),
                           ("bcalls", "fst (List.nth brokens %d)" % i),
                           ("bexit", "snd (List.nth brokens %d)" % i)]:
            names.append("%s_%d" % (name, i))
            script.append('print_endline "@@%s_%d";;' % (name, i))
            script.append("%s;;" % expr)
    script.append('print_endline "@@entries";;')
    script.append("entries;;")
    names.append("entries")
    env = dict(os.environ, TODO_FIXTURE=FIXTURE)
    proc = subprocess.run(
        ["opam", "exec", "--switch=effect4", "--", "ocaml", "-noprompt", "-I",
         os.path.join(BUILD, ".effect4_eff.objs/byte"), os.path.join(BUILD, "effect4_eff.cma")],
        input="\n".join(script) + "\n", capture_output=True, text=True, env=env, check=True)
    # each marker's own print answers "- : unit = ()"; it is not a value of the fixture
    text = re.sub(r"^- : unit = \(\)\n", "", proc.stdout, flags=re.M)
    parts = re.split(r"^@@(\w+)\n", text, flags=re.M)
    values = {}
    for k in range(1, len(parts), 2):
        name, body = parts[k], parts[k + 1]
        m = re.match(r"- : (.*?) =\s(.*)", body, flags=re.S)
        if not m:
            sys.exit("fixture_to_ml: no value printed for %s:\n%s" % (name, body[:400]))
        # the toplevel names a program's type by Eff_wire's alias; rocq-of-ocaml reads the
        # module without Eff_wire, so the type is written as the alias's expansion
        ty = m.group(1).strip().replace("Eff_wire.program", "Eff_types.native_op Eff_types.eff")
        values[name] = (ty, m.group(2).strip())
    missing = [n for n in names if n not in values]
    if missing:
        sys.exit("fixture_to_ml: missing %s" % missing)
    with open(out, "w") as f:
        f.write("(* GENERATED by docs/research/2026-10-16-itrees/gen/fixture_to_ml.py from\n"
                "   ocaml/engine/test/todo/todo-host.txt (Lean's bytes). Do not edit. *)\n\n")
        f.write("let count = %d\n\n" % count)
        for n in names:
            ty, v = values[n]
            f.write("let %s : %s =\n  %s\n\n" % (n, ty, v))
    print("wrote %s: %d values" % (out, len(names)))

if __name__ == "__main__":
    main(sys.argv[1])
