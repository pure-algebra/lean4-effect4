(* extract_map.ml -- Rocq extraction directives that send each translated program type back to
   the OCaml type it came from.

   What it is: rocq-of-ocaml translated ocaml/eff/eff_types.ml (split by split_types.ml) into
   E4.Eff_types. Extracting Rocq code over those types would write a second copy of every type.
   This tool reads eff_types.ml and prints one `Extract Inductive` per variant and per record, so
   extracted code uses `Eff_types.val_` itself, and an E4_host provider, which speaks
   Eff_types, can answer the extracted meaning's calls. Type abbreviations need nothing: Rocq
   unfolds them. A record maps to the OCaml record through a building function and a matching
   function. Depends on: compiler-libs (Parse).

   Properties:
   M1  Every variant and record of the input gets exactly one directive, its constructors in
       declaration order.                                                    by construction
   M2  The extracted program type-checks against effect4_eff: the extraction's build is the
       test (the receipt's commands).                                        tested

   Run: ocamlfind ocamlopt -package compiler-libs.common -linkpkg extract_map.ml -o extract_map
        ./extract_map eff_types.ml > EffExtract.v *)

open Parsetree

let read_file path =
  let ic = open_in_bin path in
  let s = really_input_string ic (in_channel_length ic) in
  close_in ic;
  s

(* A field that rocq-of-ocaml renamed (a leading underscore before an OCaml keyword-like name) is
   still the OCaml field it came from; the directive names OCaml's. *)
let directive (d : type_declaration) : string option =
  let name = d.ptype_name.txt in
  match d.ptype_kind with
  | Ptype_variant cs ->
    let ctor c = Printf.sprintf "\"Eff_types.%s\"" c.pcd_name.txt in
    Some
      (Printf.sprintf "Extract Inductive E4.Eff_types.%s => \"Eff_types.%s\" [ %s ]." name name
         (String.concat " " (List.map ctor cs)))
  | Ptype_record fields ->
    let fs = List.map (fun f -> f.pld_name.txt) fields in
    let tuple = String.concat ", " fs in
    let build =
      Printf.sprintf "(fun (%s) -> ({ %s } : Eff_types.%s))" tuple
        (String.concat "; " (List.map (fun f -> Printf.sprintf "Eff_types.%s = %s" f f) fs)) name
    in
    let case =
      Printf.sprintf "(fun g (r : Eff_types.%s) -> g %s)" name
        (String.concat " " (List.map (fun f -> Printf.sprintf "r.Eff_types.%s" f) fs))
    in
    Some
      (Printf.sprintf "Extract Inductive E4.Eff_types.%s.record => \"Eff_types.%s\" [ \"%s\" ] \"%s\"."
         name name build case)
  | Ptype_abstract | Ptype_open -> None

let () =
  let structure = Parse.implementation (Lexing.from_string (read_file Sys.argv.(1))) in
  print_endline "(* GENERATED by docs/research/2026-10-16-itrees/gen/extract_map.ml from ocaml/eff/eff_types.ml. *)";
  print_endline "From Stdlib Require Import Extraction.";
  print_endline "Require E4.Eff_types.";
  List.iter
    (fun item ->
      match item.pstr_desc with
      | Pstr_type (_, decls) -> List.iter (fun d -> Option.iter print_endline (directive d)) decls
      | _ -> ())
    structure
