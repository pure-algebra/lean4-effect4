(** * Extract: the meaning as OCaml, answered by any host function

    [run_n] runs a program's meaning ([Denote.meaning]) with its cells as a state and each host
    row answered by a host function: a row's position, its request and the host's state, to an
    exit and the next state, or [None] where the host does not answer (a frontier). It records
    each call. The OCaml driver ([gen/itree_lane.ml]) wraps an [E4_host] provider as such a
    function, so the providers of the to-do lane, the typed host written in OCaml among them,
    answer the extracted meaning.

    The extraction uses the estate's own program types: [EffExtract] (generated by
    [gen/extract_map.ml] from [ocaml/eff/eff_types.ml]) sends each translated type back to its
    OCaml original. [nat] and [Z] become OCaml [int], and Rocq strings OCaml strings
    ([ExtrOcamlNatInt], [ExtrOcamlZInt], [ExtrOcamlNativeString]); each is an assumption of the
    extracted code about OCaml's [int] and [string], outside any proof here. The fuel is a
    computing device of the driver. *)

From Stdlib Require Import List ZArith Extraction.
From Stdlib Require ExtrOcamlBasic ExtrOcamlNatInt ExtrOcamlZInt ExtrOcamlNativeString.
Import ListNotations.
From ITree Require Import ITree Basics.Basics Events.State.
Import ITreeNotations Basics.Basics.Monads.
Require Import RocqOfOCaml.RocqOfOCaml.
Require Import E4.Eff_types E4.Denote E4.Run E4.EffExtract.

(** A host for extraction. *)
Definition host (S : Type) : Type := int -> val_ -> S -> option (exitv * S).

(** The host as a handler of the rows, recording each answered call; no answer is a frontier. *)
Definition h_host {S : Type} (f : host S) : RowE ~> stateT (S * list call) (itree WaitE) :=
  fun T e =>
    match e in RowE T return stateT (S * list call) (itree WaitE) T with
    | Row i v => fun st =>
      match f i v (fst st) with
      | Some (a, s') => Ret ((s', snd st ++ [(i, v, a)]), a)
      | None => ITree.bind (trigger (Waits i v)) (fun x : void => match x with end)
      end
    end.

Definition run_with {S : Type} (f : host S) (p : eff native_op) (s : S)
    : itree WaitE ((S * list call) * (cells * exitv)) :=
  interp_state (h_host f) (interp_state h_cells (meaning p) []) (s, []).

(** What a driver reads: the host's last state, the calls, and the root's exit. *)
Definition run_n {S : Type} (fuel : nat) (f : host S) (p : eff native_op) (s : S)
    : outcome (S * list call * exitv) :=
  match observe_n fuel (run_with f p s) with
  | Done (st, (_, ex)) => Done (fst st, snd st, ex)
  | Waiting i v => Waiting i v
  | Unfinished => Unfinished
  end.

(** The translation library's [int] is [Z], which [ExtrOcamlZInt] already writes as OCaml's
    [int]; written as its own type it would read [type int = int], a cycle. *)
Extract Inlined Constant RocqOfOCaml.Basics.int => "int".
Extract Inlined Constant RocqOfOCaml.RocqOfOCaml.int => "int".

Extraction "itree_run.ml" run_n exit_image exit_of_image.
