from pathlib import Path
import hashlib, json
r = Path(__file__).resolve().parent
pins = json.loads((r / "pins.json").read_text())
for item in pins["files"]:
    assert hashlib.sha256((r / "snapshot" / item["path"]).read_bytes()).hexdigest() == item["sha256"]
eff = (r / "snapshot/src/Effect4/Program/Eff.lean").read_text()
printer = (r / "snapshot/src/Effect4/Codegen/Print.lean").read_text()
reader = (r / "snapshot/src/Effect4/Codegen/Read.lean").read_text()
segments = []
def part(text, start, end, source):
    section = text[text.index(start):text.index(end)]
    segments.append({"source": source, "start": start, "end": end, "sha256": hashlib.sha256(section.encode()).hexdigest()})
    return section
text = """-- Generated by extract.py from the hash-pinned WIP. Research probe only.
import Effect4.Codegen.Print
import Effect4.Codegen.Read
import Effect4.Program.Native
import TypeScript.Render

namespace Co6bProbe
open Effect4 Effect4.Program
open Effect4.Machine.Env (Requirement)
open TypeScript (Expr)
variable {Op : Type}

"""
text += part(eff, "inductive DefRole where", "/-- The row a definition declares:", "Program/Eff.lean")
text += part(printer, "def DefDecl.effTy", "/-- **A definition as a module constant**", "Codegen/Print.lean")
text += part(printer, "structure Service where", "/-- The printed program as a declaration block", "Codegen/Print.lean")
text += part(printer, "def serviceNamesFault", "/-- Print an admitted program against its row table.", "Codegen/Print.lean")
text += part(reader, "def readServiceMethod", "/-- A definition's declaration and its printed body", "Codegen/Read.lean")
text += (r / "Controls.inc").read_text()
(r / "ExtractedServices.lean").write_text(text)
(r / "extraction.json").write_text(json.dumps({"adaptation": "Fresh namespace and local DefRole/DefDecl; exact source segments unchanged. Existing compiled base supplies unchanged type conversion, target AST and renderer. This does not rebuild the WIP module, readModule, or admitModule.", "segments": segments}, indent=2) + "\n")
print("Extracted exact source segments into Co6bProbe")
