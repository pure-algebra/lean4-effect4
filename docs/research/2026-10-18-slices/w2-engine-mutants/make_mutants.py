def main():
    OUT.mkdir(parents=True, exist_ok=True)
    seen = set()
    for mid, name, old, new, what in SPECS:
        assert mid not in seen, mid
        seen.add(mid)
        rel = E + name
        text = (ROOT / rel).read_text()
        count = text.count(old)
        if count != 1:
            sys.exit(f'{mid}: snippet occurs {count} times in {rel}')
        mutated = text.replace(old, new, 1)
        diff = difflib.unified_diff(
            text.splitlines(keepends=True), mutated.splitlines(keepends=True),
            fromfile='a/' + rel, tofile='b/' + rel, n=3)
        body = ''.join(diff)
        header = f'{mid} {name}: {what}\n\n'
        (OUT / f'{mid}.patch').write_text(header + body)
    print(f'{len(SPECS)} patches written to {OUT}')


if __name__ == '__main__':
    main()
