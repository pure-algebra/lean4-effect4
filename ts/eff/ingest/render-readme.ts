// Generated documentation is data from the three Lean-owned tables.
import { readFileSync, writeFileSync } from "node:fs"
import { createHash } from "node:crypto"
import { execFileSync } from "node:child_process"
import { heads, rows } from "../profile.gen.ts"
import { forms } from "../forms.gen.ts"
import { taxonomy } from "../taxonomy.gen.ts"
const root = new URL("../../../", import.meta.url)
const inputs = ["ts/eff/ingest/render-readme.ts", "ts/eff/profile.gen.ts", "ts/eff/forms.gen.ts", "ts/eff/taxonomy.gen.ts"].sort()
const digest = createHash("sha256").update(inputs.map(p => `file ${p} ${createHash("sha256").update(readFileSync(new URL(p, root))).digest("hex")}\n`).join("")).digest("hex")
const rev = execFileSync("git", ["describe", "--always", "--dirty"], { cwd: root, encoding: "utf8" }).trim()
const toolchain = readFileSync(new URL("lean-toolchain", root), "utf8").trim().split(":v").at(-1)
const table = (columns: readonly string[], data: readonly (readonly string[])[]) => `| ${columns.join(" | ")} |\n| ${columns.map(() => "---").join(" | ")} |\n${data.map(row => `| ${row.join(" | ")} |`).join("\n")}\n`
const output = `<!-- cut-from: rev=${rev} toolchain=${toolchain} inputs=${digest} -->
<!-- GENERATED by ts/eff/ingest/render-readme.ts; do not edit. -->
# Ingest

Two independent syntax readers turn admitted Effect TypeScript into Eff documents,
ordered service-key tables and canonical wire bytes. The compiler reader uses
TypeScript 5.9.2; the other normalizes oxc 0.147.0 nodes into the existing fragment
reader. Shared tables contain data; the engines share no recognition code.

From the repository root, run:

\`bun ts/eff/ingest/cli.ts recognize path --engine both --bytes\`

The command streams one JSON record per file in path order. Use \`--format tsv\`
for a tabular envelope. Exit status is 0 for agreement, 1 for disagreement and 2
when the command cannot run. \`--cache DIR\` enables the private content/pins memo;
unchanged size and modification time locate a cached digest without reading source.
Use \`--force\` to bypass that index. Gates always read fresh inputs. Workers process
at most 500 files and are replaced. Bun 1.3.14 and Node 22.23.2 are checked at entry.
For Node, pass \`--experimental-transform-types --disable-warning=ExperimentalWarning\`.

\`bash scripts/check-ingest.sh\` freshly constructs the printer and foreign corpora,
compares each with its original JSON and wire oracle, checks foreign key tables,
runs source-edit tests, verifies refusal reachability and checks OCaml decoding.
Printer-image entrypoints are test seams and never fallbacks for foreign admission.
Only source locations are excluded from comparisons across source edits; same-input
engine comparisons retain the entire lifted record.

Regenerate this file with \`bun ts/eff/ingest/render-readme.ts\`; \`--check\` verifies drift.
The following tables are generated from the profile, forms and taxonomy.

## Direct heads

${table(["Head"], heads.map(h => [h]))}
## Native rows

${table(["Operation", "Head", "Kind", "Trailing atoms"], rows.map(r => [JSON.stringify(r.op), r.row.spelling, r.row.kind, r.row.trailing.join(", ")]))}
## Derived forms

${table(["Form", "Head", "Arity", "Pinned definition"], forms.rows.map(r => [r.id, r.head, JSON.stringify(r.arity), r.citation]))}
## Refusals

${table(["Code", "Status", "Meaning"], taxonomy.map(r => [r.code, r.status, r.detail]))}`
const target = new URL("./README.md", import.meta.url)
const stable = (s: string) => s.replace(/rev=\S+/, "rev=informational")
if (process.argv.includes("--check")) {
  if (stable(readFileSync(target, "utf8")) !== stable(output)) throw new Error("ingest README drift")
  console.log("PASS ingest README: generated tables and source stamp match")
} else writeFileSync(target, output)
